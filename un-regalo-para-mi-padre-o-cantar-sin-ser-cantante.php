<h3></h3></p>

<p class="text-justify">El videoclip se estrenó el día en el que sería su cumpleaños número 65, días después había cumplido años miguel bose, ¡yo no lo podía creer! No lo sabía, no sabía que cumplían años en la misma semana y que prácticamente tenían la misma edad (mi papá y bosé). Pero lo más sorprendente es que días después se conmemoraba el lamentable hecho de la desaparición de los tres estudiantes de cine de mi alma mater, el CAAV, la universidad de medios audiovisuales...  ¡todo junto! con días de diferencia, bueno que si lo planeo no me sale.  Ese día mientras los hombres encapuchados nos interrogaban yo no hacia mas que imaginarme en una casa de seguridad, privado de mi libertad junto con todo mi equipo de producción, aunque nada mas hayamos sido 3 personas en total, y todo por un tonto videoclip pensaba yo en ese momento; digo si hayamos estado haciendo un documental  informativo sobre el narcotráfico y eso temas pantanosos, uno sabe muy bien por default  el riesgo que existe al ejercer una labor periodística y de investigación en este país, pero morir por un video clip homenaje a mi padre con la canción de miguel bose de fondo, pues tampoco era como que valiera la pena la desaparición. Sin embargo, menos mal que todo fue un susto nada más. </p>

<p class="text-justify">En el mundo del futbol existe un término hoy muy de moda que se llama post futbol, y que no es otra cosa que las cosas “valga la redundancia” de todo lo que sucede alrededor del futbol, menos lo que pasa en la cancha, eso sí es futbol. </p>

<p class="text-justify">Mi historia paréntesis de lo que pudo ser un levantón, bien podría ser parte de una historia de post futbol. Mi padre en vida amó con pasión el futbol, pero de una forma sana sin rayar en un fanatismo absurdo, entrenaba diario, organizaba equipos infantiles donde intento hacerme participe, en el cual fracase estrepitosamente, de hecho, alguna vez hice un cortometraje con un trauma infantil, que tengo, como eje principal de la historia. De hecho no habia caido en cuenta que suelo usar el futbol como elemento narrativo dentro de mis historias audiovisuales y ahora sé por qué en los cortometrajes de temática gay que he realizado, los protagonistas siempre se enamoran de un chico heterosexual que juega futbol; porque es para mí una búsqueda de una aprobación paterna, quizas, o la búsqueda de un amor que nunca podrá ser. Mi padre vio muchos de mis trabajos en video, pero ese cortometraje (el del trauma infantil) nunca me atreví a mostrárselo, porque pensé que podría herirlo, (ya que él era parte del trauma mismo) y el arte debe sanar no debe herir, o no debería al menos no accidentalmente. </p>

<p class="text-justify">Con el paso del tiempo, me he dado cuenta lo mucho que me interesa el futbol, o más bien el post futbol, porque sí estoy enterado de toda la parafernalia que sucede alrededor de este deporte, pero más de las historias macabras y tristes como la de Cesar Andrade jugador promesa que perdió una pierna luego de un accidente automovilístico, la trágica historia de salvador cabañas, así como su presunto affair con uno de sus compañeros, el origen de Pele, y también de Mesi y Maradona y más recientemente el lamentable hecho de Joa Maleck. Aun así sigo sin saber cuanto dura un partido de futbol ni de cuantos jugadores hay en la cancha ni de que es un tiro de esquina o un saque de meta, solo me sé los términos, pero no los entiendo. Supongo que lo que me importa del futbol son sus historias que, sí son inspiradoras per se, pero que también se vuelven mitos aterradores. Y debido a mi aspiración a convertirme en un director de cine es que traigo al futbol de esa forma en mis historias, porque para mí el futbol ha sido aterrador. </p>

<p class="text-justify">El día que grabe la escena donde estoy interpretando a mi padre jugando futbol entendí una cosa, mi padre quería de regalo no que cantase, quería que fuera yo quien lo interpretara a él en el video clip, porque por alguna razón los dos actores prácticamente ya confirmados cancelaron su participación de último momento (y no es por nada, pero no suelo dejar clavos sueltos ni confiar en cualquier persona que se diga actor, pero bueno hasta el mejor cazador se le va la liebre supongo). Luego de ver las tomas en el ordenador vi ciertos elementos que a parecían a cuadro y que me hacían pensar que ese día mi padre sí estuvo ahí conmigo como si él haya dicho “capo lo tienes que hacer tú, yo quiero que lo hagas tú, yo voy a estar contigo apoyándote, es más yo quiero salir en tu video y ese será mi regalo”. Después de su muerte él me visito varias veces en sueños, pero después de estrenar el video clip ya no volvió. Entendí que había trascendido ya que en el último sueño se despedía de alguna manera de mí.   </p>

