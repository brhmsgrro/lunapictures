            <article class="editorial-body">
                <p class="drop-cap">Nochevieja. Terminaba de arreglarme mientras me miraba al espejo: llaves, cartera, celular, todo en los bolsillos. Cerré la puerta de mi departamento y me dirigí a casa de mi hermana, donde sería la cena. Ellos llevaban años separados; mi madre lo toleraba mucho menos de lo que él a ella. Sin embargo, él nunca había sido rencoroso, nunca tuvo un problema real con ella, pero ese día ambos habían decidido limar asperezas y los dos estarían ahí amablemente.</p> 

                <p>Al verlo entrar a la casa, luego de haber estado convaleciente por la diabetes unos meses atrás, lo vi muy flaco y, por primera vez, lo vi avejentado. Mi mamá solo lo saludó con frialdad. Durante la cena, todo transcurrió con normalidad y ambos nos contaron historias de muy al principio de su relación. Finalmente, después de haberlo pasado bien, nos abrazamos, y lloré amargamente en su hombro y en el de todos también. Sabía que vendría lo inevitable: un aviso, tal vez, de que su tiempo y el de todos como familia aquí en la tierra estaba por concluir.</p>
                
                <p>Pasaron unos meses y, próximo a cumplir 63, estaba prácticamente recuperado, jovial y con ese ánimo de vivir que le caracterizaba. Le organicé su fiesta de cumpleaños. Se rumoraba que todos entraríamos en cuarentena debido al COVID… así que dije: es ahora o nunca. Parte de mi regalo era cantarle "Te amaré", versión karaoke de Miguel Bosé, a mi papá. Pero en el bar de mi madre todo estaba remodelándose y preparándose para una ampliación; había música, pero no el equipo de micrófono con pantallas para cantar con una pista, etcétera. "Bueno, ni modo", pensé. "Igual eso no es tan importante". Invité a varios de mis amigos a celebrar conmigo, pero la mayoría no asistió debido al temor que empezaba a circular por el virus de moda. Mi familia es muy pequeña, pero prácticamente todos estuvimos ahí. Al terminar, todos nos fuimos a dormir.</p>
                
                <p>Yo estaba en el baño y él estaba junto a mí. No entendía por qué, me daba mucha vergüenza. De repente, todo el escenario cambiaba y ahora estaba en medio de la sala de mi casa, en la que había crecido, pero yo con mi edad actual. Mi papá me explicaba que había que hacer ese ritual. Al voltear hacia el marco de la puerta, una criatura humanoide de no más de 15 cm, de lo que parecía ser jengibre seco, entró corriendo y deslizándose por toda la habitación. Mi padre y yo buscamos la forma de atraparlo y someterlo… finalmente lo conseguíamos. Mi madre solo veía impávida, sin hacer ni decir nada.</p>
                
                <p>"El ritual, las instrucciones, capo", así me decía de cariño mi papá. Me decía "capo de capos", porque al nacer pensó llamarme Abraham Caro (como Caro Quintero, el capo de capos; mi madre no permitió que me pusieran ese nombre). Yo encontré entre los bolsillos de mi pantalón una hoja con instrucciones o rezos que leía en voz alta, mientras mi padre abría el vientre del pequeño hombre de jengibre, que para este momento era más una especie de pequeño hombre sapo. Introducíamos algo dentro de su cuerpo y, con esfuerzos ante el forcejeo de la criatura, él lograba coser la piel de su cuerpo con el objeto dentro.</p>
                
                <p>"Familiares del señor Abraham L.". La enfermera me sacó del recuerdo de esa pesadilla que había tenido meses atrás. Para esto, la pandemia ya estaba en su máximo esplendor; hacía un año de la Nochevieja donde lloré en el hombro de mi padre. Había llegado la Navidad y el 31 de diciembre nuevamente, y él pasó todo este tiempo en el hospital. Ese fin de año el festejo fue amargo, si es que apenas hicimos algo. Aun así, pasaron 15 días más, y se resistía a irse. No quería irse, deseaba mucho vivir, le encantaba vivir. Hasta que finalmente vi a mi madre llorar desconsolada con el anuncio de su muerte: había fallecido de COVID.</p>
                
                <p>No podía creer lo profundo del llanto de mi madre, ya que siempre decía lo mucho que le irritaba su presencia y cada vez que podía le hacía un desprecio para no compartir el mismo espacio con él. "Estoy seguro de que mi padre estaría riéndose ahora mismo de estar observando esto", pensé… y de seguro habría dicho: "¡No que no, mujer, no que no me amabas, María!". Siempre tuvo un sentido del humor muy ácido, mismo que mis hermanos y yo le heredamos y que tanto molestaba a mi madre principalmente.</p>
                
                <p>En mi familia había esa extraña tradición y don maldito de soñar con el futuro: premoniciones y avisos que vienen a nosotros en forma de mensajes encriptados y que, con el paso del tiempo, hemos aprendido a descifrar. Pero ese sueño en especial no supe en su momento cómo interpretarlo ni qué significaba: el del hombre de jengibre. Ahora, frente a sus cenizas, en la misa de despedida de sus restos, lo había entendido todo. Solo mis dos muchachos, mis hermanos con sus parejas y mi madre estuvimos ahí. Todo era un tema burocrático debido a las restricciones sanitarias que limitaban las reuniones multitudinarias, así como la prohibición de enterrar un cuerpo; tenía que ser incinerado, no hubo más.</p>
                
                <p>Hoy lamento nunca haber tocado ese tema con él: cómo veía él su funeral. Sin embargo, ese tema no le gustaba tocarlo, pese a su negro sentido del humor. "¿Y si te vas tú primero?", me decía. "Claro, es probable que cruce la calle y me atropelle un auto y muera", respondía yo. "Pero por estadística y probabilidades, te toca a ti primero". Él solo movía la cabeza de un lado a otro en señal de desaprobación.</p>
                
                <p>Nunca he sido muy bueno regalando cosas, ya que en la búsqueda de ser original termino siendo muy "random", y mis regalos siempre son atípicos, pero también muy simbólicos. En una ocasión, a alguien muy especial le regalé un cuaderno, y la persona se desconcertó tanto. "¿Un cuaderno? ¿Quién regala un pinche cuaderno?", nunca lo dijo, pero lo vi en su cara. En mi defensa debo decir que esta persona lo tenía todo. ¿Qué le regalas a alguien que lo tiene todo? O al menos eso pensé yo en ese momento. Así que un cuaderno podría ser un inicio; era el símbolo de comenzar algo, de escribir una nueva historia, de un nuevo comienzo, de estudiar algo nuevo. Creo que no lo supo interpretar correctamente. Así que, después, le regalé un libro para que no pensara que yo era tacaño.</p>
                
                <p>"Me gustaría tener tu seguridad… cantas horrible", me dijo uno de mis amigos después de escuchar el master de la canción. "Eres como una cabra berreante… qué valiente". —Qué bonitas cosas me dices—, respondí yo. Mi amigo era de esos amigos que no sabes muy bien por qué son tus amigos; alguien que te dice las cosas de un modo muy sutil, te soba, te soba y después suelta un chingadazo. Aun así, seguiría con mi plan. Había contratado un actor, tenía la locación, todo sería fácil, pensé yo, pan comido. Había grabado escenas de playback, pero me faltaba la escena de un personaje que representara a mi padre dentro de la trama del videoclip.</p>
                
                <p>Mi padre de joven había… ¡no, amado!, lo que le sigue, al fútbol. Misma actividad que nos separó desde que yo era muy pequeño, ya que él intentó hacer que yo amase su pasatiempo, pero cada que corría tropezaba con el balón, caía al suelo y lloraba. Siempre le molestó eso de mí. Ahora supongo que pensaba que era un debilucho y fue motivo suficiente para distanciarnos. Tiempo después me descubrí homosexual, y yo empecé a tener resentimiento hacia él; nuestra relación fue muy ríspida durante toda mi adolescencia. Finalmente llegó la madurez y las cosas mejoraron. Con el tiempo, y luego de terminar mis estudios universitarios, me volví un productor audiovisual; había hecho cortometrajes y videoclips para bandas de rock locales de mi ciudad, y videos empresariales y corporativos.</p>
                
                <p>Pero ahora, en los altavoces de mi computadora, sonaba "Te amaré", un cover de Miguel Bosé. Yo nunca había cantado y menos había grabado nada. Era mi voz y me entristecía profundamente oír la falta de talento para el canto de mi parte, pero al mismo tiempo algo en mí crecía a modo de orgullo, de saber que estaba esforzándome en romper mis limitaciones para lograr algo para lo que no era apto. Era como verme a mí mismo de niño, llorando tirado en el suelo con el balón frente a mí, pero esta vez tenía la posibilidad de decirle: "Levántate, vamos, yo sé que puedes hacerlo, una vez más, no te rindas".</p>
                
                <blockquote>
                    "El día que grabé la escena donde estoy interpretando a mi padre jugando fútbol entendí una cosa: mi padre quería de regalo no que cantase, quería que fuera yo quien lo interpretara a él."
                </blockquote>
                
                <p>Así que, aparte de productor audiovisual, estaba ahora por grabar lo que sería el primer videoclip de mi nada prometedora carrera como estrella de la música pop. "¿Y por qué esta canción?", preguntó el director de fotografía mientras nos dirigíamos a la locación. "Mi padre amaba a Miguel Bosé, era de sus artistas favoritos, decía que le parecía muy guapo. Además, mi papá cantaba y no lo hacía mal, y la canción habla de eso: del amor que le tiene un hijo a su padre, aunque sea de carácter difícil, con tus defectos y virtudes, con tu no saber perder, te amaré", citaba yo.</p>
                
                <p>Para mí era una carta de amor, así como de disculpa. Ahora entendía que nunca me había esforzado lo suficiente para ser un buen hijo y prácticamente estaba por cumplir treinta y seis, así que algo en mí había madurado, aunque ya era muy tarde para reponer el daño.</p>
                
                <p>Dos veces, el que sería el actor para el personaje principal en la trama de mi videoclip, me había cancelado de último momento. Pero como productor audiovisual, uno siempre tiene que tener un as bajo la manga. Así que dije: "Vale, lo haré yo". Usé una peluca para simular ser otra persona, me puse un outfit que simulaba ser un uniforme de fútbol, y empecé a correr torpemente detrás del balón por la llanura, con el terror de tropezar y caer. Pero esta vez no sucedió. "¡Corte!", gritó el director de fotografía. "A ver, checa la toma". En ese momento me di cuenta de que era aún peor como futbolista que como cantante. "Pero servía", dije yo, y ya sabía cómo arreglaría mi falta de talento para el balompié: todo se arreglaría con cortes rápidos en postproducción.</p>
                
                <p>Terminamos de grabar y, al dirigirnos de regreso a casa por el camino, fuimos interceptados por un grupo de gente enmascarada con pasamontañas. "La puta que nos parió", pensé lo peor. Imaginaba un levantón de los que hace el crimen organizado, y un montón de cosas de terror pasaron por mi cabeza. Nos preguntaron qué hacíamos en ese lugar tan alejado y el porqué de mi vestimenta, y nos pidieron bajáramos de la camioneta.</p>
                
                <p>Finalmente me tranquilicé después de ver gente de la Fiscalía Ministerial. Al parecer, había más gente que antes no había visto: hombres, mujeres, jóvenes, buscando un cuerpo. No había mencionado que el lugar donde grabamos este video era una barranca alejada de la ciudad, con un fondo montañoso, el lugar idóneo para deshacerte de evidencia incriminatoria. Después de un montón de preguntas, los judiciales nos dejaron ir. Que, por cierto, no estaban vestidos como policías, sino como civiles; eso asusta más a uno, ya que a los narcos les gusta vestirse como judiciales encapuchados, y a la policía le gusta pasar desapercibida. Vamos, que si no ves su placa o gafete, ni te enteras, y entonces, para estas alturas, vaya usted a saber quién nos estaba interrogando. "Hay, Abraham, dónde me vienes a traer", me increpó el fotógrafo. Sonreí tímidamente con vergüenza. Él siguió manejando, yo con un subidón de adrenalina, pero ya más tranquilo.</p>

