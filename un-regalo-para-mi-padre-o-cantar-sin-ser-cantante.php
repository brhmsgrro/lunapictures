          <p class="text-justify">Noche vieja: Terminaba de arreglarme mientras me miraba al espejo; llaves, cartera celular, todo en los bolsillos cerré la puerta de mi departamento y me dirigí a casa de mi hermana donde seria la cena. Ellos llevaban años separados, mi madre lo toleraba mucho menos de lo que él a ella…sin embargo él nunca había sido rencoroso, nunca tuvo problema con ella realmente, pero ese día ambos habían decidido limar asperezas y los dos estarían ahí amablemente.  Al verlo entrar a la casa luego de haber estado convaleciente por diabetes unos meses atrás, lo vi muy flaco y por primera vez lo vi avejentado, mi mamá solo lo saludo con frialdad. Durante la cena todo trascurrió con normalidad y ambos nos contaron historias de muy al principio de su relación, finalmente después de haberlo pasado bien, nos abrazamos, y llore amargamente en su hombro y en el de todos también, sabía que vendría lo inevitable, un aviso tal vez de que su tiempo y el de todos como familia aquí en la tierra estaba por concluir.  </p> 

          <div class="col-md-3 animate-box" data-animate-effect="fadeInLeft">
          
          <img data-lazy="https://media.giphy.com/media/Tu8GciWggvvVDFs46q/giphy.gif" class="img-responsive" alt="un regalo para papá">
          
