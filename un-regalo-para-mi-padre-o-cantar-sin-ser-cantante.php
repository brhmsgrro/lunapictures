<p class="text-justify">Pasaron unos meses y próximo a cumplir 63 estaba prácticamente recuperado, jovial y con ese ánimo de vivir que le caracterizaba, le organice su fiesta de cumpleaños. Se rumoraba también que todos entraríamos en cuarentena debido al covid… así que dije es ahora o nunca, parte de mi regalo era cantarle “te amaré” versión karaoke de Miguel Bosé a mi papá, pero en el bar de mi madre todo estaba remodelándose y preparándose para una ampliación, así que había música, pero no el equipo de micrófono con pantallas para cantar con una pista etc. Bueno ni modo pensé, igual eso no es tan importante, invité a varios de mis amigos a celebrar conmigo, pero la mayoría no asistió debido a el temor que empezaba a circular por el virus de moda. Mi familia es muy pequeña pero prácticamente todos estuvimos ahí. Al terminar todos nos fuimos a dormir.  </p></br></br>

<h3></h3></p>


 <p class="text-justify">Yo estaba en el baño y él estaba junto a mí, no entendía porque, me daba mucha vergüenza, de un de repente todo el escenario cambiaba y ahora estaba en medio de la sala de mi casa en la que había crecido pero yo con mi edad actual, mi papá me explicaba que había que hacer ese ritual, al voltear hacia el marco de la puerta, una criatura humanoide de no mas de 15 cm de lo que parecía ser jengibre seco, entro corriendo y deslizándose por toda la habitación, mi padre y yo buscamos la forma de atraparlo y someterlo… finalmente lo conseguíamos.. mi madre solo veía impávida sin hacer ni decir nada… “el ritual, las instrucciones capo!!“-así me decía de cariño mi papá- me decía capo de capos, porque al nacer pensó llamarme Abraham Caro (como Caro Quintero el capo de capos) -mi madre no permitió que me pusieran ese nombre-. Yo encontré entre los bolsillos de mi pantalón una hoja con instrucciones o rezos que leía en voz alta mientras mi padre habría el vientre del pequeño hombre de jengibre que para este momento era más una especie de pequeño hombre sapo, introducíamos algo dentro de su cuerpo y con esfuerzos ante el forcejeo de la criatura, él lograba coser la piel de su cuerpo con el objeto dentro. </p></br>

<p class="text-justify">“Familiares del señor Abraham L” la enfermera me saco del recuerdo de esa pesadilla que había tenido meses atrás, para esto la pandemia ya estaba en su máximo esplendor; hacia un año de la noche vieja donde lloré en el hombro de mi padre, había llegado navidad y el 31 de diciembre nuevamente, y él pasó todo este tiempo en el hospital. Ese fin de año el festejo fue amargo si es que apenas hicimos algo. Aun así, pasaron 15 días más, y se resistía a irse, no quería irse él deseaba mucho vivir le encantaba vivir. Hasta que finalmente vi a mi madre llorar desconsolada con el anuncio de su muerte, habia fallecido de covid. No podía creer lo profundo del llanto de mi madre, ya que siempre decía lo mucho que le irritaba su presencia y cada vez que podía le hacia un desprecio para no compartir el mismo espacio con él, -estoy seguro de que mi padre estaría riéndose ahora mismo de estar observando esto- pensé… y de seguro habría dicho:  ”¡no que no mujer, no que no me amabas maría!” siempre tuvo un sentido del humor muy ácido, mismo que mis hermanos y yo le heredamos y que tanto molestaba a mi madre principalmente. </p>

En mi familia había esa extraña tradición y don maldito, de soñar con el futuro, premoniciones y avisos que vienen a nosotros en forma avisos encriptados y que con el paso del tiempo hemos aprendido a descifrar, pero ese sueño en especial no supe en su momento como interpretarlo ni que significaba, el del hombre de jengibre. Ahora frente a sus cenizas, en la misa de despedida de sus restos, lo había entendido todo. Solo mis dos muchachos y mis hermanos con sus parejas y mi madre estuvimos ahí, todo era un tema burocrático debido a las restricciones sanitarias por parte de las autoridades que limitaban las reuniones multitudinarias, así como la prohibición de enterrar un cuerpo, tenía que ser incinerado, no hubo más. Hoy lamento nunca haber tocado ese tema con él, en como veía él su funeral, sin embargo, ese tema no le gustaba tocarlo pese a su negro sentido del humor. “¿Y si te vas tu primero?” me decía; “claro es probable que cruce la calle y me atropelle un auto y muera” respondía yo “pero por estadística y probabilidades te toca a ti primero” él solo movía la cabeza de un lado a otro en señal de desaprobación. </p>
</br>




<p class="text-justify">Nunca he sido muy bueno regalando cosas, ya que en la búsqueda de ser original termino siendo muy “random” y mis regalos siempre son atípicos, pero también son muy simbólicos. En una ocasión a alguien muy especial le regalé un cuaderno, y la persona se desconcertó tanto “un cuaderno quien regala un pinche cuaderno” nunca lo dijo, pero lo vi en su cara… En mi defensa debo decir que esta persona lo tenía todo, ¿qué le regalas a alguien que lo tiene todo? o al menos eso pensé yo en ese momento, así que un cuaderno, podría ser un inicio; era el símbolo de comenzar algo de escribir una nueva historia de un nuevo comienzo de estudiar algo nuevo, creo que no lo supo interpretar correctamente. Así que después le regale un libro para que no pensara que yo era tacaño.  </p></br>



<p class="text-justify">“me gustaría tener tu seguridad… cantas horribles” me dijo uno de mis amigos, después de escuchar el master de la canción “eres como una cabra berreante… que valiente” -que bonitas cosas me dices- respondí yo. Mi amigo era de esos amigos que no sabes muy bien porque son tus amigos, alguien que te dice las cosas de un modo muy sutil te soba te soba y después suelta un chingadazo. Aun así, seguiría con mi plan, había contratado un actor, tenia la locación, todo sería fácil, pensé yo, pan comido. Había grabado escenas de Play back, pero me faltaba, la escena de un personaje que representara a mi padre dentro de la trama del video clip.  
</p></br>

<p class="text-justify">Mi padre de joven había ¡no, amado!, lo que le sigue, al futbol, misma actividad que nos separó desde que yo era muy pequeño. Ya que sí intento hacer que yo amase su pasatiempo pero cada que corría tropezaba con el balón, caía al suelo y lloraba; siempre le molesto eso de mí, ahora supongo que pensaba que era un debilucho y fue motivo suficiente para distanciarnos, tiempo después me descubrí homosexual, y yo empecé a tener resentimiento hacia él, nuestra relación fue muy ríspida durante toda mi adolescencia, finalmente llego la madurez y las cosas mejoraron. Con el Tiempo y luego de terminar mis estudios universitarios me volví un productor audiovisual; había hecho cortometrajes, y video clips para bandas de rock locales de mi ciudad, y videos empresariales y corporativos. </p>


<p class="text-justify">Pero ahora en los altavoces de mi computadora sonaba “te amaré” un cover de miguel bose; yo nunca había cantado y menos había grabado nada, era mi voz y me entristecía profundamente oír la falta de talento para el canto de mi parte, pero al mismo tiempo algo en mi crecía a modo de orgullo de mi mismo de saber que estaba esforzándome en romper mis limitaciones para lograr algo para lo que no era apto, era como verme a mi mismo de niño llorando tirado en el suelo con el balón frente a mí, pero esta vez tenía la posibilidad de decirle levántate vamos yo se que puedes hacerlo, una vez mas no te rindas.  </p>

<p class="text-justify">Así que aparte de productor audiovisual estaba ahora por grabar lo que seria el primer video clip de mi nada prometedora carrera como estrella de la música pop, “y porqué esta canción” preguntó el director de fotografía, mientras nos dirigíamos a la locación, “mi padre amaba a miguel bose, era de sus artistas favoritos, decía que le parecía muy guapo, además de que mi papá cantaba y no lo hacia mal, y la canción habla de eso, de el amor que le tiene un hijo a su padre, aunque sea de carácter difícil, con tus defectos y virtudes con tu no saber perder te amere” citaba yo. Para mí era una carta de amor, así como de disculpa… ahora entendía que nunca me había esforzado lo suficiente para ser un buen hijo y prácticamente estaba por cumplir treinta y seis, así que algo en mi había madurado, aunque ya era muy tarde para reponer el daño. </p>

<p class="text-justify">Dos veces el que sería el actor para el personaje principal en la trama de mi videoclip, me había cancelado de ultimo momento, pero como productor audiovisual uno siempre tiene que tener un haz bajo la manga; Así que dije “vale, lo hare yo” usé una peluca para simular ser otra persona, me puse un outfit que simulaba ser un uniforme de futbol, y empecé a correr torpemente detrás del balón por la llanura, con el terror de tropezar y caer, pero esta vez no sucedió. “¡corte! grito el director de fotografía, haber checa la toma” en ese momento me di cuenta de que era aún peor como futbolista que como cantante, “pero servía” dije yo, y ya sabía cómo arreglaría mi falta de talento para el balompié, todo se arreglaría con cortes rapidos en post producción. Terminamos de grabar y al dirigirnos de regreso a casa por el camino fuimos interceptados por un grupo de gente enmascarada con pasamontañas. “La puta que nos pario” pensé lo peor… imaginaba un levantón de los que hace el crimen organizado y montón de cosas de terror pasaron por mi cabeza, nos preguntaron que hacíamos en ese lugar tan alejado y el porque de mi vestimenta y nos pidieron bajáramos de la camioneta.</p>

<p class="text-justify">Finalmente me tranquilice después de ver gente de la fiscalía ministerial… al parecer había más gente también que antes no había visto; hombre mujeres, jóvenes, buscando un cuerpo, no había mencionado que el lugar donde grabamos este video era una barranca alejada de la ciudad, con un fondo montañoso el lugar idóneo para deshacerte de evidencia incriminatoria.  Después de un montón de preguntas los judiciales nos dejaron ir, que por cierto no estaban vestidos como policías si no como civiles, eso asusta más a uno ya que a los narcos les gusta vestirse como judiciales encapuchados, y a la policía le gusta pasar desapercibida vamos que si no ves su placa o gafete ni te enteras, y entonces para estas alturas vaya uste a saber quién nos estaba interrogando.  “hay Abraham donde me vienes a traer” me increpo el fotógrafo, sonreí tímidamente con vergüenza, el siguió manejando, yo con un subidón de adrenalina, pero ya más tranquilo.  </p>

