                <p>El videoclip se estrenó el día en el que sería su cumpleaños número 65. Días después, había cumplido años Miguel Bosé. ¡Yo no lo podía creer! No lo sabía, no sabía que cumplían años en la misma semana y que prácticamente tenían la misma edad (mi papá y Bosé). Pero lo más sorprendente es que días después se conmemoraba el lamentable hecho de la desaparición de los tres estudiantes de cine de mi alma mater, el CAAV, la universidad de medios audiovisuales... ¡Todo junto! Con días de diferencia. Bueno, que si lo planeo, no me sale.</p>
                
                <p>Ese día, mientras los hombres encapuchados nos interrogaban, yo no hacía más que imaginarme en una casa de seguridad, privado de mi libertad junto con todo mi equipo de producción (aunque nada más hayamos sido tres personas en total), y todo por un tonto videoclip, pensaba yo en ese momento. Digo, si hubiéramos estado haciendo un documental informativo sobre el narcotráfico y esos temas pantanosos, uno sabe muy bien, por default, el riesgo que existe al ejercer una labor periodística y de investigación en este país. Pero morir por un videoclip homenaje a mi padre con la canción de Miguel Bosé de fondo, pues tampoco era como que valiera la pena la desaparición. Sin embargo, menos mal que todo fue un susto nada más.</p>
                
                <p>En el mundo del fútbol existe un término hoy muy de moda que se llama "post-fútbol", y que no es otra cosa que las cosas —valga la redundancia— de todo lo que sucede alrededor del fútbol, menos lo que pasa en la cancha. Eso sí es fútbol.</p>
                
                <p>Mi historia, paréntesis de lo que pudo ser un levantón, bien podría ser parte de una historia de post-fútbol. Mi padre, en vida, amó con pasión el fútbol, pero de una forma sana, sin rayar en un fanatismo absurdo. Entrenaba diario, organizaba equipos infantiles donde intentó hacerme partícipe, en el cual fracasé estrepitosamente. De hecho, alguna vez hice un cortometraje con un trauma infantil que tengo como eje principal de la historia. De hecho, no había caído en cuenta de que suelo usar el fútbol como elemento narrativo dentro de mis historias audiovisuales, y ahora sé por qué: en los cortometrajes de temática gay que he realizado, los protagonistas siempre se enamoran de un chico heterosexual que juega fútbol. Porque es, para mí, una búsqueda de una aprobación paterna, quizás, o la búsqueda de un amor que nunca podrá ser.</p>
                
                <p>Mi padre vio muchos de mis trabajos en video, pero ese cortometraje (el del trauma infantil) nunca me atreví a mostrárselo, porque pensé que podría herirlo (ya que él era parte del trauma mismo), y el arte debe sanar, no debe herir. O no debería, al menos, no accidentalmente.</p>
                
                <p>Con el paso del tiempo, me he dado cuenta de lo mucho que me interesa el fútbol, o más bien el post-fútbol. Porque sí estoy enterado de toda la parafernalia que sucede alrededor de este deporte, pero más de las historias macabras y tristes, como la de César Andrade, jugador promesa que perdió una pierna luego de un accidente automovilístico; la trágica historia de Salvador Cabañas, así como su presunto affair con uno de sus compañeros; el origen de Pelé, y también de Messi y Maradona, y más recientemente el lamentable hecho de José Manuel Mireles (o referencias a tragedias deportivas recientes). Aun así, sigo sin saber cuánto dura un partido de fútbol, ni de cuántos jugadores hay en la cancha, ni de qué es un tiro de esquina o un saque de meta. Solo me sé los términos, pero no los entiendo. Supongo que lo que me importa del fútbol son sus historias, que sí son inspiradoras per se, pero que también se vuelven mitos aterradores. Y debido a mi aspiración a convertirme en un director de cine, es que traigo al fútbol de esa forma en mis historias, porque para mí el fútbol ha sido aterrador.</p>
                
                <p>El día que grabé la escena donde estoy interpretando a mi padre jugando fútbol entendí una cosa: mi padre quería de regalo no que cantase, quería que fuera yo quien lo interpretara a él en el videoclip. Porque, por alguna razón, los dos actores prácticamente ya confirmados cancelaron su participación de último momento (y no es por nada, pero no suelo dejar cabos sueltos ni confiar en cualquier persona que se diga actor, pero bueno, hasta el mejor cazador se le va la liebre, supongo). Luego de ver las tomas en el ordenador, vi ciertos elementos que aparecían a cuadro y que me hacían pensar que ese día mi padre sí estuvo ahí conmigo, como si él haya dicho: "Capo, lo tienes que hacer tú. Yo quiero que lo hagas tú, yo voy a estar contigo apoyándote. Es más, yo quiero salir en tu video, y ese será mi regalo".</p>
                
                <p>Después de su muerte, él me visitó varias veces en sueños, pero después de estrenar el videoclip, ya no volvió. Entendí que había trascendido, ya que en el último sueño se despedía de alguna manera de mí.</p>

