					<p class="text-justify">Alguna vez me contrataron para cubrir un evento de sociales, ya saben, ir tomar fotos a un evento familiar, en fin, todo normal, todo chévere, yo inexperto e improvisado como en casi en todo lo que hago -y sin temor a dios, ahora que lo creo- acepté a cubrir dicho evento. </p> 

          <p class="text-justify">Terminaba de salir la carrera de medios audiovisuales que si bien no era una licenciatura enfocada en fotografía sí lo era en cuestiones artísticas, luz, composición, color, semiótica, etc., etc.  Lo tengo claro; creo que puedo con el reto, hay que hacerlo, pensé. Menciono lo anterior porque es importante ya que había cursado esa carrera gracias a una beca, no contaba con dinero para invertir y no me había hecho de equipo ya hasta en los últimos cuatrimestres de la misma. Mis prácticas y ejercicios lo pude lograr gracias a varios de mis compañeros, pero en especial a uno al que siempre le estaré eternamente agradecido, y del cual estuve completamente enamorado, prácticamente toda la licenciatura, pero esa es otra historia.</p>
          <p class="text-justify">Bueno, en fin, estudiar esta carrera me había abierto muchas puertas y muchas de ellas remuneradas tan es así que, poco a poco pude pagar mi primer cámara, también cabe aclarar que venia de un fracaso profesional anterior como emprendedor, así que no, aun no podía permitirme llenarme de equipo. Cubrí dicho evento con lo más básico: un canon 7d y un lente 18-55mm el que viene de cajón, no más. </p>

<p class="text-justify">Era plena tarde de invierno, con el sol poniéndose, pero aun así la luz era bastante fuerte, faltaba poco para primavera, hacia frio, de esos fríos que hacen que la luz del cielo se torne completamente azul. Regular los parámetros de la cámara fue difícil, en especial por la luz. El espacio; la terraza de un bar. Tan fuerte era la luz que, aunque todas las cortinas metálicas del local se habían dispuesto a la mitad, la luz de la resolana entraba rebotaba en el piso y daba unos contraste muy marcados e intensos en las fotografías, me gustaba, pero aun así no lograba compensar todos los valores para una correcta exposición, y tener ese estilo de “fotografía de sociales” digamos; había muchas sombras y claro oscuros. </p>

<p class="text-justify">El tiempo avanzaba y mientras pensaba todo esto, yo disparaba y disparaba sin cesar y sin conseguir una correcta exposición, tira en raw, pensé, el revelado digital te ayudara, buena idea, me dije a mi mismo. Aunque lo ideal habría sido usar filtros, un lente 50mm, que se yo… incluso, sugerirle a los invitados se colocasen en dirección a la luz, ya que por la resolana que lastima los ojos, obviamente, todos estaban de espalda a la luz del sol (quedándoles sus rostros a contra luz). Sin embargo, esa no fue una opción; un buen fotógrafo lo soluciona desde la cámara, pensé yo ingenuamente. Disparé y disparé hasta conseguir “tomas artísticas” o al menos, con buenos parámetros de luz que después podrían ser mejorados en postproducción, encuadres correctos etc. </p>

<p class="text-justify">Terminé, me ofrecieron de comer, acepté ya que andaba corto de dinero o como se dice era un “artista muerto de hambre”, claro, si no, no eres “artista”, hay que vivir eso de los manifiestos al cien.  Me pagaron, terminé y me fui. También hice algunas tomas de video, pero eso fue otra historia que tal vez después contaré. </p>

<p class="text-justify">Ya en casa me dispuse a revisar los archivos y aunque había buenas tomas no todas merecían ser reveladas e impresas; que es lo que había quedado con el cliente, imprimir las mejores y enmarcarlas en un marco de madera muy mono, especial para los recuerdos familiares, esos que como se sabe “duraran… para toda la vida” …  </p>

<p class="text-justify">Tomé aproximadamente 100 fotografías, pero salieron 10 o 12 que merecían ser impresas que, a pesar de mis limitaciones técnicas, se salvaban, creía yo y deberían tener la oportunidad de formar parte de los recuerdos familiares. Qué curioso pensé; ya que mientras hice mi trabajo, los mismos parientes de los clientes, tomaron fotos y videos con sus celulares; cuántas de esas fotos realmente les importará a todos los dueños de esos aparatos inteligentes, como para conservarlas en sus memorias o en el mejor de los casos, imprimirlas.  Y qué pasaría en el supuesto de que el celular fuese robado o extraviado, esos recuerdos simplemente se habrán perdido para siempre. Eso me paso una vez con una laptop en la que tenía mucho trabajo creativo y decenas de fotografías de mis hijos cuando estos, aún eran muy pequeños. Tan es así que de esa época solo conservó una sola fotografía y es porque la había impreso algunos meses antes ya que adoraba lo bien que había salido. </p>


<p class="text-justify">Regresando a lo del revelado de imágenes, que si yo, no tenía experiencia como fotógrafo de sociales, menos como post productor de imágenes, pero, aun así, me guie por mi instinto; ¿qué te dicen las imágenes? pensé una vez más…, yo me dejé ir moviéndole a los valores, algunas de estas fotografías tomaron vida por si mismas y ellas, sí, literalmente ellas, me dijeron como querían ser expuestas… que raro. Así seguí con cada una.</p>

<p class="text-justify">Finalmente, aunque las imágenes tenían un estilo en cuestión, éstas habían agarrado colores completamente diferentes unas a las otras, algunas se veían mas “alegres” y otras se veían mas “oscuras”, no en temas de luz si no, en un tema de energías, de aura, por así decirlo; las personas transmitían ciertas vibras y era mi criterio (o mis prejuicios) los que juzgaban, perdón, los que dictaban los valores o no se que de que se yo, pero todas las imágenes resultaron diferentes, no había homogeneidad entre ellas digamos, en fin.</p>

<p class="text-justify">Una maestra de fotografía, bueno más bien de video me había dicho; “no importa como haya quedado la toma, tú termina el trabajo, quede como quede, tú termina” y es que un trabajo, no esta terminado, hasta que es expuesto a ojos críticos, “especializados” o gente de “a pie”; tu obra termina cuando conoce la luz pública, sí. Aunque esto, no es del todo cierto, ya que la obra la finaliza realmente cuando el espectador le da un significado a tu obra digamos que es la significancia que esta tiene para el publico la que la hace concluir.  </p>
<p class="text-justify">Así que siguiendo este consejo decidí imprimirlas posteriormente mostrárselas a un amigo de toda la vida y que suele ser sumamente despiadado, pero honesto: “Están bien culeras” me dijo; “la luz es horrible…” -que bonitas cosas me dices- le respondí yo sardónicamente, -Mmm… vale, ¿Gracias? -… me fui a mi casa desecho y ya con miedo de que el cliente viera el resultado final. Vamos que, del miedo, pensé sinceramente, en escapar del país y darme a la fuga para no tener que entregar tan asqueroso trabajo.</p>

<p class="text-justify">Pero ahí estaba yo, parado frente a la puerta de la casa del cliente tocando el timbre, la bolsa negra de plástico en la que estaba guardado el marco de 30 x 30 no revelaba el contenido de las fotos. Abrieron a la puerta salió la esposa, llamo a su marido y juntos vieron el trabajo, el silencio fue apenante … en su rostro se veía la desaprobación de estas, “¿porque se ven así?” … “Así cómo?” pregunte, “como oscuras, tristes, apagadas, y con colores muy chillantes a la vez.”  …le explique que era un tipo de fotografía que se enfocaba en el aura… y veía las energías de las personas, (eso para no tener que decirle; estoy quebrado no tengo para comprar más equipo fotográfico, págueme mañana no se si comeré) … “¿me estás diciendo, que puedes ver el aura de las personas?” me dijo, “Mmm…este no, que la fotografía o mas bien el revelado de la fotografía se enfoca en esos principios” … respondí. “Que feas fotos” dijo la esposa, “talvez es que no sabes tomar fotografías... ¡ve!, en está como salgo yo, ¡oscuro!”  “¡talvez así se ve tu energía!” Respondí en un arrebato de estupidez y sinceridad al mismo tiempo; ya que había visto durante la fiesta como trataba a su mujer, “no me gustan -respondió la esposa- no te vamos a pagar por ello” … “En realidad ya está pagado el 70% solo faltaría el 30”, dije yo, el esposo volteo a ver a su mujer, “bien pues no te vamos a pagar por esto. y menos para que nos digas que somos una mierda de personas” … “¡¿Mierda de personas?!” En qué momento dije eso, pensé ... “no, yo quise decir” … “Palabras más palabras menos, es más tu tampoco me caíste bien, desde que te vi, acepté porque mi esposa te recomendó” … “Porque una amiga te recomendó conmigo de hecho…” le increpó la esposa.</p>

<p class="text-justify">Apenado y humillado ya no supe que decir ... “bueno está bien entonces me voy” -Solo déjanos eso por favor- dijo el esposo, “pero ¿no acaban de decir que están horribles” conteste, -Sí, pero ya pagamos por eso- Ok, pensé “bueno ¿puedo al menos conservar el marco?” pregunte “Es que ya no tengo para pagarlo” -Esta bien- respondieron ambos. </p>

<p class="text-justify">Así que empecé a desmontar las fotografías del marco.  Sentía como si un fondo musical llegara de forma extra diegética; solo música de elevador se escuchaba en mi mente. Sali de ahí sin ganas de seguir en la fotografía, de hecho, dejé los sociales para siempre, sentí que talvez no eran para mí. Pero aprendí una lección muy importante: un buen fotógrafo no es el que toma buenas fotos si no el que tiene un equipo para tomar buenas fotos… en fin. En la fotografía todo es caro y lo que yo cobré en ese entonces apenas me dio para pagar el mes de alquiler, ya no digamos un 50mm, del más barato, pero es que tampoco me iban a pagar la millonada si es que apenas estaba empezando. Supongo que ese tipo de cosas solo me suceden a mí. </p>



