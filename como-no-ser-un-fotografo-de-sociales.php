            <article class="editorial-body">
                <p class="drop-cap">Alguna vez me contrataron para cubrir un evento de sociales. Ya saben: ir a tomar fotos a una reunión familiar. En fin, todo normal, todo chévere. Yo, inexperto e improvisado como en casi todo lo que hago —y sin temor a Dios, ahora que lo recuerdo—, acepté cubrir dicho evento.</p> 

                <p>Recién salía de la carrera de Medios Audiovisuales que, si bien no era una licenciatura enfocada exclusivamente en fotografía, sí lo era en cuestiones artísticas: luz, composición, color, semiótica, etcétera. Lo tengo claro: "Creo que puedo con el reto, hay que hacerlo", pensé. Menciono lo anterior porque es importante: había cursado esa carrera gracias a una beca, no contaba con dinero para invertir y no me había hecho de equipo hasta en los últimos cuatrimestres. Mis prácticas y ejercicios los pude lograr gracias a varios de mis compañeros, pero en especial a uno al que siempre le estaré eternamente agradecido (y del cual estuve completamente enamorado prácticamente toda la licenciatura, pero esa es otra historia).</p>
                
                <p>Estudiar esta carrera me había abierto muchas puertas, y muchas de ellas remuneradas. Tan es así que, poco a poco, pude pagar mi primera cámara. Cabe aclarar que venía de un fracaso profesional anterior como emprendedor, así que no, aún no podía permitirme llenarme de equipo. Cubrí dicho evento con lo más básico: una Canon 7D y un lente 18-55mm, el que viene de cajón. Nada más.</p>
                
                <p>Era plena tarde de invierno, con el sol poniéndose, pero aun así la luz era bastante fuerte. Faltaba poco para la primavera y hacía frío, de esos fríos que hacen que la luz del cielo se torne completamente azul. Regular los parámetros de la cámara fue difícil, en especial por la luz. El espacio: la terraza de un bar. Tan fuerte era la luz que, aunque todas las cortinas metálicas del local se habían dispuesto a la mitad, la luz de la resolana entraba, rebotaba en el piso y daba unos contrastes muy marcados e intensos en las fotografías. Me gustaba, pero aun así no lograba compensar todos los valores para una correcta exposición y tener ese estilo de "fotografía de sociales". Había muchas sombras y claros oscuros.</p>
                
                <p>El tiempo avanzaba y, mientras pensaba todo esto, yo disparaba y disparaba sin cesar, sin conseguir una correcta exposición. "Tira en RAW", pensé, "el revelado digital te ayudará". Buena idea, me dije a mí mismo. Aunque lo ideal habría sido usar filtros, un lente 50mm, qué sé yo… incluso, sugerirle a los invitados colocarse en dirección a la luz, ya que por la resolana que lastima los ojos, obviamente, todos estaban de espaldas al sol (quedándoles sus rostros a contraluz). Sin embargo, esa no fue una opción. "Un buen fotógrafo lo soluciona desde la cámara", pensé yo, ingenuamente. Disparé hasta conseguir "tomas artísticas" o, al menos, con buenos parámetros de luz que después podrían ser mejorados en postproducción.</p>
                
                <p>Terminé. Me ofrecieron de comer y acepté, ya que andaba corto de dinero o, como se dice, era un "artista muerto de hambre". Claro, si no, no eres "artista"; hay que vivir eso de los manifiestos al cien. Me pagaron, terminé y me fui.</p>
                
                <p>Ya en casa, me dispuse a revisar los archivos. Aunque había buenas tomas, no todas merecían ser reveladas e impresas, que es lo que había quedado con el cliente: imprimir las mejores y enmarcarlas en un marco de madera muy mono, especial para los recuerdos familiares, esos que, como se sabe, "durarán… para toda la vida".</p>
                
                <p>Tomé aproximadamente 100 fotografías, pero salieron 10 o 12 que merecían ser impresas que, a pesar de mis limitaciones técnicas, se salvaban, creía yo, y deberían tener la oportunidad de formar parte de los recuerdos familiares. Qué curioso pensé: mientras hice mi trabajo, los mismos parientes de los clientes tomaron fotos y videos con sus celulares. ¿Cuántas de esas fotos realmente les importará a todos los dueños de esos aparatos inteligentes como para conservarlas en sus memorias o, en el mejor de los casos, imprimirlas? ¿Y qué pasaría en el supuesto de que el celular fuese robado o extraviado? Esos recuerdos simplemente se habrán perdido para siempre. Eso me pasó una vez con una laptop en la que tenía mucho trabajo creativo y decenas de fotografías de mis hijos cuando estos aún eran muy pequeños. Tan es así que de esa época solo conservo una sola fotografía, y es porque la había impreso algunos meses antes, ya que adoraba lo bien que había salido.</p>
                
                <p>Regresando a lo del revelado de imágenes: si yo no tenía experiencia como fotógrafo de sociales, menos como postproductor de imágenes. Pero, aun así, me guié por mi instinto. "¿Qué te dicen las imágenes?", pensé una vez más. Yo me dejé ir moviéndole a los valores. Algunas de estas fotografías tomaron vida por sí mismas y ellas, sí, literalmente ellas, me dijeron cómo querían ser expuestas… qué raro. Así seguí con cada una.</p>
                
                <p>Finalmente, aunque las imágenes tenían un estilo en cuestión, estas habían agarrado colores completamente diferentes unas a las otras. Algunas se veían más "alegres" y otras se veían más "oscuras". No en temas de luz, sino en un tema de energías, de aura, por así decirlo. Las personas transmitían ciertas vibras y era mi criterio (o mis prejuicios) los que juzgaban, perdón, los que dictaban los valores. Todas las imágenes resultaron diferentes; no había homogeneidad entre ellas, digamos. En fin.</p>
                
                <blockquote>
                    "Están bien culeras", me dijo. "La luz es horrible".
                </blockquote>
                
                <p>Una maestra de fotografía (bueno, más bien de video) me había dicho: "No importa cómo haya quedado la toma, tú termina el trabajo. Quede como quede, tú termina". Y es que un trabajo no está terminado hasta que es expuesto a ojos críticos, "especializados" o gente "de a pie". Tu obra termina cuando conoce la luz pública. Aunque esto no es del todo cierto, ya que la obra la finaliza realmente cuando el espectador le da un significado; digamos que es la significancia que esta tiene para el público la que la hace concluir.</p>
                
                <p>Así que, siguiendo este consejo, decidí imprimirlas y posteriormente mostrárselas a un amigo de toda la vida que suele ser sumamente despiadado, pero honesto. "Están bien culeras", me dijo. "La luz es horrible". —Qué bonitas cosas me dices—, le respondí yo sardónicamente. —Mmm… vale, ¿gracias?—. Me fui a mi casa deshecho y ya con miedo de que el cliente viera el resultado final. Vamos, que del miedo, pensé sinceramente en escapar del país y darme a la fuga para no tener que entregar tan asqueroso trabajo.</p>
                
                <p>Pero ahí estaba yo, parado frente a la puerta de la casa del cliente, tocando el timbre. La bolsa negra de plástico en la que estaba guardado el marco de 30 x 30 no revelaba el contenido de las fotos. Abrieron la puerta, salió la esposa, llamó a su marido y juntos vieron el trabajo. El silencio fue apenante. En su rostro se veía la desaprobación. "¿Por qué se ven así?", preguntaron. "¿Así cómo?", pregunté. "Como oscuras, tristes, apagadas y con colores muy chillantes a la vez".</p>
                
                <p>Le expliqué que era un tipo de fotografía que se enfocaba en el aura… y veía las energías de las personas (eso, para no tener que decirle: "estoy quebrado, no tengo para comprar más equipo fotográfico, págueme mañana, no sé si comeré"). "¿Me estás diciendo que puedes ver el aura de las personas?", me dijo. "Mmm… este, no, que la fotografía, o más bien el revelado de la fotografía, se enfoca en esos principios", respondí. "Qué feas fotos", dijo la esposa. "Tal vez es que no sabes tomar fotografías... ¡Ve!, en esta, ¿cómo salgo yo? ¡Oscura!". "¡Tal vez así se ve tu energía!", respondí en un arrebato de estupidez y sinceridad al mismo tiempo, ya que había visto durante la fiesta cómo trataba a su mujer. "No me gustan", respondió la esposa. "No te vamos a pagar por ello". "En realidad ya está pagado el 70%, solo faltaría el 30%", dije yo. El esposo volteó a ver a su mujer. "Bien, pues no te vamos a pagar por esto. Y menos para que nos digas que somos una mierda de personas". "¿Mierda de personas?", pensé. ¿En qué momento dije eso? "No, yo quise decir…". "Palabras más, palabras menos. Es más, tú tampoco me caíste bien. Desde que te vi, acepté porque mi esposa te recomendó", le increpó la esposa.</p>
                
                <p>Apenado y humillado, ya no supe qué decir. "Bueno, está bien, entonces me voy". "Solo déjanos eso, por favor", dijo el esposo. "Pero, ¿no acaban de decir que están horribles?", contesté. "Sí, pero ya pagamos por eso". Ok, pensé. "Bueno, ¿puedo al menos conservar el marco?", pregunté. "Es que ya no tengo para pagarlo". "Está bien", respondieron ambos.</p>
                
                <p>Así que empecé a desmontar las fotografías del marco. Sentía como si un fondo musical llegara de forma extradiegética; solo música de elevador se escuchaba en mi mente. Salí de ahí sin ganas de seguir en la fotografía. De hecho, dejé los sociales para siempre. Sentí que tal vez no eran para mí. Pero aprendí una lección muy importante, cargada de ironía: <mark>un buen fotógrafo no es el que toma buenas fotos, sino el que tiene el equipo para tomar buenas fotos.</mark> En fin. En la fotografía todo es caro, y lo que yo cobré en ese entonces apenas me dio para pagar el mes de alquiler, ya no digamos un 50mm, del más barato. Pero es que tampoco me iban a pagar la millonada, si es que apenas estaba empezando. Supongo que ese tipo de cosas solo me suceden a mí.</p>

