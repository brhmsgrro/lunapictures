            <article class="editorial-body">
                <p class="drop-cap">Me encontraba llorando, como si no hubiera mañana, desconsolado en el baño de ese edificio. Era la primera vez que visitaba el DF (ahora la CDMX), al menos la primera vez que iba solo y tenía un motivo para hacerlo: el edificio CENEVAL. Justo unos minutos antes, había presentado el examen de titulación por medio del acuerdo 286 emitido por la SEP.</p> 

                <p>Los cuatro sinodales asignados para mi caso fueron implacables. Revisaron de "pe a pa" mi tesina e hicieron un centenar de preguntas que respondí de la mejor manera posible, salvo algunas finales que literalmente eran demasiadas. Precisamente, el examen fue oral; tenía que defender lo escrito en el papel, que previamente fue revisado por el consejo de maestros, obvio.</p>
                
                <p>Había hecho mi mejor esfuerzo, pero evidentemente no fue el suficiente. Al terminar el examen, simplemente huí de aquel lugar. Llegué corriendo al baño, cerré la puerta y me desmoroné. Nunca sentí tanta presión e impotencia al mismo tiempo. Ahora que lo veo a distancia no fue tan duro, pero sí fue difícil llegar hasta el final: escribir la tesina en máximo 20 días, no haber dormido nada la noche anterior y el viaje de Guadalajara a la Ciudad de México me habían dejado agotado.</p>
                
                <p>De algún modo logré calmarme y salí del cubículo. Por suerte, durante ese momento no hubo nadie más en el baño. Mojé mi cara, sentía que ardía en fiebre, sequé las lágrimas, sacudí mi nariz, me puse unos lentes negros y salí a la sala de recepción a esperar el dictamen. Me desparramé en el sofá; el traje que había comprado días antes era incómodo. La cabeza me daba vueltas.</p>
                
                <p>Un hombre de unos 50 años, sentado en el sillón de enfrente, esperaba a su esposa, quien también estaba presentando su examen en ese momento. El hombre observó el estado en el que había salido del baño y empezó a platicar conmigo: "Muy duros, ¿verdad?". Asentí con la cabeza y reí débilmente. Me habló de todo el proceso, de lo mucho que se empeñaron en escribir bien la tesina. Yo apenas si escuchaba.</p>
                
                <p>Recordaba mi salida rumbo a México. Era 8 de diciembre del 2017. El caso tenía que estar resuelto, asignado 20 días antes, y debía cargarse junto a otros documentos a una plataforma. Gestionar boletos, trazar la ruta... justo terminé, entregué todo y subí "rayando". El tiempo límite era ese día hasta las 3:00 pm. A veces pienso que me gusta la adrenalina, porque siempre me pasan este tipo de cosas.</p>

                <p>Ahora solo debía preparar la presentación oficial en PowerPoint para el 9 de enero del 2019. Sin embargo, pocos días después de subir los documentos, un ladrón entró a robar la bodega de mi negocio. Una trabajadora vio cómo se llevaba el portátil con toda mi información personal, financiera y la dichosa presentación a medio hacer.</p>
                
                <p>Suerte la mía, pensaba mientras tomaba un expreso doble a las 4:30 en el café del aeropuerto. Hacía cabriolas y maldecía el sistema operativo de la computadora de mi hermana (una Mac), entre el cansancio, el estrés y la lentitud del internet. Escuché por los altavoces la salida de mi vuelo. Ya en el avión, apenas avancé unas cuantas diapositivas. Por suerte, el documento del caso de estudio se guardó en línea y pude descargarlo.</p>
                
                <p>No había mencionado que la licenciatura a acreditar era la de Mercadotecnia. Años atrás tuve problemas con una materia que nunca pude aprobar: Investigación de Operaciones. Me aplicaron el artículo 35, lo que significa que prácticamente estás fuera de la licenciatura. Faltaban dos semestres para concluir cuando eso ocurrió. En aquel entonces no le di la importancia que requería porque estaba montando un restaurante de comida rápida. Con ese negocio pasé 4 años... pero esa es otra historia. De cualquier forma, esa fue la razón por la cual no concluí mis estudios en tiempo y forma: el famoso <mark>coste de oportunidad</mark>.</p>
                
                <blockquote>
                    "Te guste o no, la carrera y el oficio no están peleados, pero sí duermen separados. Gente muy lista valida cuándo eres apto para recibir un título, pero el dinero en tus manos acredita cuánto sabes en realidad sobre la vida misma."
                </blockquote>
                
                <p>Salí del aeropuerto y llegué al edificio CENEVAL a las 10:00 am, con mucho tiempo de sobra. Salí a buscar un hotel y, para no hacer el cuento más largo, terminé entrando en un motel por un par de horas solo para poder bañarme. Logré llegar con 15 minutos de sobra, pero aún no había quemado el CD con la presentación; de hecho, no estaba completamente acabada.</p>

                <p>Me anuncié para que supieran que estaba "listo" y me dieron un pase de espera. Me senté en la sala, abrí la computadora, y una voz a mis espaldas dijo mi nombre. "¿Sí?", pregunté con terror. "Señor, necesito su presentación en un disco", me dijo la chica. "No la tengo", respondí avergonzado. "Bueno, veré qué puedo hacer", terminó.</p>
                
                <p>Por motivos de seguridad, no se puede presentar el examen con un archivo guardado en una USB. Mi mente construía una película de ciencia ficción sobre cómo hackearían los resultados. Justo en ese momento, la sinodal representante del consejo leyó en voz alta mi nombre y los motivos por los cuales la institución no podía validar mis conocimientos como aptos para acreditar la licenciatura.</p>
                
                <p>Había llorado amargamente antes en el baño lo suficiente para no hacerlo después de escuchar el dictamen. Salí del salón y me dejé caer en un sofá libre en el recibidor principal. Antes, vi pasar a uno de los sinodales; me sonrió y me dijo: "Ánimo, no se desanime". Instantes después, me dormí por cerca de 10 minutos.</p>
                
                <p>Al día siguiente, de regreso en el taxi, platicando con el conductor, le contaba el motivo de mi visita. Me preguntaba cuál creía yo que había sido el motivo del fracaso. Yo lo sabía muy bien: no había puesto suficientes referencias y no las apuntalé bien según los formatos APA. Pero la verdadera razón fue que no tuve mi biblioteca personal cerca al momento de escribir la tesina. Durante la carrera atesoré varios libros de marketing; todo lo que sé, sabía que estaba ahí. Solo tenía que citar mis referencias. Encontrar los libros fue imposible porque ni siquiera recordaba los títulos.</p>
                
                <p>También, uno de los profesores sinodales me increpó el uso de un lenguaje cotidiano en mi narrativa: "No es una novela, es un documento de investigación", me dijo. Tal vez abusé de ese recurso. Saber de dónde coger cada frase fue imposible en ese momento de presión.</p>
                
                <p>En su momento pensé dar el carpetazo al proyecto, pero finalmente entendí de qué sirve la academia y cuál es su función. Algunos compañeros de la carrera actualmente fungen como profesores de mercadotecnia, y solo el pensamiento me aterroriza: "¿Pero si nunca han montado un negocio en su vida, ellos son los que enseñan sobre ventas en las universidades? ¡Qué miedo!".</p>
                
                <p>Igualmente, estudié con un montón de catedráticos así. De hecho, el mismo profesor sinodal que me dijo que no escribía una novela, tenía la facha de no haber emprendido ningún proyecto en su vida. ¿Qué sabía él de estrategias y montar un emprendimiento? Pero entendí que gente así es la que valida los conocimientos de los profesionales que a su vez hacen el oficio.</p>
                
                <p style="font-size: 1.25rem; font-weight: 600; color: #121212; margin-top: 3rem; border-top: 1px solid #e2e2e2; padding-top: 2rem;">
                    En fin, aún tengo esa espina de que la academia valide que realmente sé de mercadotecnia. Supongo que solo tengo que aprender a redactar bien en APA.
                </p>
