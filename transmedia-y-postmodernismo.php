					<p class="text-justify">Ciertamente aquel día no había mucho que hacer así que me dispuse a visitar el museo de arte moderno aquí en mi ciudad, cabe mencionar que la historia que estoy por contar sucedió allá por el 2015. Ese año sin duda fue el año de remedios varo, ya que a partir de ese entonces (al menos yo en lo personal) supe quien era el autor(a) de la mayoría de las portadas en los libros de texto gratuito que había llevado a lo largo de mi educación básica; sí ese año fue de Remedios… mi Remedios Varo. Ese día por lo visto también una serie de estudiantes asistieron a esta exposición liderados por una profesora de letras supongo; no, ya recordé que impartía el taller de narrativa, lo recuerdo porque escuche hablar a dos alumnos acerca de la tarea que les habían encomendado su profesora para esa materia, entre muchas mas que llevaban, al parecer estos estudiantes cursaban la carrera de artes visuales con enfoque en video, así que me imagino eso era parte importante de su formación, porque seamos sinceros las artes visuales van desde la fotografía, pintura, diseño gráfico, imprenta, video etc.… en fin, creo yo era sí importante.</p> 

          <p class="text-justify">Por muchos años quien ha llevado la batuta como pintora estandarte del arte mexicano, había sido sin duda Frida khalo, que vamos hasta tiene su biopic, no así, Remedios Varo, y que hoy por hoy ha sido redescubierta y revalorada, y que vamos sinceramente es infinitamente mejor pintora que Frida, sin embargo esta no es tan famosa, digamos que más por una cuestión de mercadeo y comercialización que otra cosa, pero sin duda incluso la propuesta estética de Remedios (que raya en lo surrealista) es mucho mas interesante que los autorretratos repetitivos de Frida khalo. </p>

          <p class="text-justify">Luego después descubrí también que en esta carrera hay otra materia que se lleva después y que se llama narrativa transmedia; una es taller de narrativa y la otra igual pero con el trans y el media, por lo visto no elegio mejor nombre de vanguardia ya que hoy actualmente todo es “trans”; transgénico, transexual, transgresor en fin todo lo “trans” es cool, menos las grasas trans, esas no tanto, pero todo lo demás sí …  </p>
          <div class="col-md-4 col-md-pull- animate-box" data-animate-effect="fadeInLeft">
          <img data-lazy="https://lunapictures.com.mx/images/mushasho-cansado-final-+-marco-blog1.jpg" class="img-responsive" alt="la mujer en el rio">
          </div>
          <p class="text-justify">En fin, la finalidad de la narrativa transmedia vs la narrativa tradicional, consiste en romper los formatos, no así las reglas de la narrativa, ejemplo; empezar por el final, hacer varios nudos y después el preludio y finalmente el inicio con un universo alterno, no. La narrativa transmedia trata de formatos, de video por ejemplo, y no me refiero al mp4, avi o mpeg; me refiero a los formatos de plataformas digitales, ya que estos chicos estudiaban  audiovisuales, el asunto va encaminado a contar una historia de forma diferente en diferentes formatos y para diferentes plataformas, como podría ser la historia de cenicienta en un formato televisivo, a modo de telenovela, y que por ende al tener muchos capítulos por tradición seria larga; una serie en contraparte haría uso de la economía narrativa y reduciría los diálogos al máximo en pro de dejar al lenguaje audiovisual hablar, una película lo haría igualmente pero en máximo dos horas, pero incluso esa misma historia podría volverse foto, o volverse pintura y solo tendría un plano que a su vez jugaría con las dimensiones y la sintaxis de la imagen, repito en pro de la historia. </p>

          <p class="text-justify">Recuerdo que ese día llevaba mi cámara y uno de los chicos tenia un aspecto tan cansado y curioso que recuerdo haber visto la imagen de fondo uno de los cuadros de remedios varo, por supuesto, titulado “ciencia inútil o el alquimista” (portada de uno de los libros de física en secundaria lo recuerdo perfecto) y fue entonces que surgió en mi mente una paradoja digital, llegando a casa prendí el ordenador, inspirado abrí un editor de imágenes y empecé a trabajar en esta apropiación que parte de un movimiento actualmente llamado  post modernismo.</p>

          <p class="text-justify">La narrativa transmedia nos dice que toda historia merece ser contada en diferentes formatos y en todas adquirirá un tono diferente, de mayor o menor dimensión. Lo interesante de esto es que también una historia podría ser contada en partes y en diferentes formatos, esto es que una imagen nos puede dar el inicio de la historia, un texto seguir con la misma y finalizarla con un video que emita la resolución. Una historia en partes, pero todas las partes se contarían desde diversas plataformas.</p>

          <p class="text-justify">Lo vemos actualmente con el citado arriba, postmodernismo, sin duda una buena época para hacer una retrospectiva de todo lo que se ha creado y reinterpretarlo y apropiarlo, para convertirlo en una nueva obra, algo que sin duda le sentara fatal a la creatividad de los años venideros, ya que si solo nos enfocamos en lo que ya se hizo no habrá pie para la innovación por ende habrá un estancamiento creativo sin precedentes, pero si tuviéramos que culpar a alguien podríamos empezar con Warhol y Duchamp, que sin duda propiciaron que actualmente todo sea una reinterpretación; justamente en las redes sociales si analizamos un poco con detenimiento esta generación de influencers está influenciada a su vez, mayormente, por la cultura Disney y aunque muchos artistas hacen reinterpretaciones más obscuras de estas historias rosas, en donde vemos una doble cara de la sociedad “utópicamente feliz” y “la magia Disney”, es un poco preocupante que una gran mayoría de ilustradores, pintores y artistas visuales… estén influenciado principalmente por la cultura de personajes animados, que claro no esta mal, lo que preocupa que Disney sea la fuente principal de inspiración de millones de artistas postmodernos. </p>

          <p class="text-justify">De igual forma el posmodernismo también hace uso de la narrativa transmedia ya que al tomar la obra de otro y trans formarla en otra cosa diferente, hace que la historia cambie, así como el contexto, así como el mensaje, hay creatividad hay originalidad, pero también muchas de las veces las obras son sumamente mediocres. </p>


          <p class="text-justify">Hace unos años una artista que se hacia llamar de vanguardia puso de moda un termino que no resonaba en el mundo del arte, al menos tan fuerte como lo fue después; “apropiación”. En el 2014 la pintora karla de Lara hizo una serie de pinturas sobre spider man (universo de caricaturas nuevamente) pero lo que ella hizo fue tomar una imagen de un pintor neoyorkino famoso, un cuadro sobre el hombre araña y por medio de un ordenador y proyector; proyectarlo sobre un lienzo y así empezar a pintar el cuadro, esto podría ser más una reproducción artesanal que otra cosa, pero entonces luego de la avalancha de criticas sobre su legitimidad como autora se defendió de forma magistral y en una jugada maestra (me imagino que diseñada por sus asesores) llamo a su trabajo una apropiación de la obra, finalmente en un giro inesperado salió bien librada y no paso a mayores, luego de esto este término se volvió famoso, ella también pero su fama solo duro 5 minutos, bueno no, creo que sí ha sobrevivió a la fama de ese incidente, pero si lo analizamos un poco su fama se debe más a este incidente que a su talento u originalidad, igual lo hiciera Duchamp con el mingitorio, o Warhol con las cajas de jabones. </p>

