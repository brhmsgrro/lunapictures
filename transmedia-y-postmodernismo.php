            <article class="editorial-body">
                <p class="drop-cap">Ciertamente, aquel día no había mucho que hacer, así que me dispuse a visitar el Museo de Arte Moderno aquí en mi ciudad. Cabe mencionar que la historia que estoy por contar sucedió allá por el 2015. Ese año, sin duda, fue el año de Remedios Varo. A partir de ese entonces (al menos yo, en lo personal) supe quién era la autora de la mayoría de las portadas en los libros de texto gratuito que había llevado a lo largo de mi educación básica. Sí, ese año fue de Remedios… mi Remedios Varo.</p> 

                <p>Ese día, por lo visto, también una serie de estudiantes asistió a esta exposición, liderados por una profesora de letras, supongo. No, ya recordé: impartía el taller de narrativa. Lo recuerdo porque escuché hablar a dos alumnos acerca de la tarea que les habían encomendado para esa materia, entre muchas más que llevaban. Al parecer, estos estudiantes cursaban la carrera de Artes Visuales con enfoque en video, así que me imagino que eso era parte importante de su formación. Porque seamos sinceros, las artes visuales van desde la fotografía, la pintura, el diseño gráfico, la imprenta, el video, etcétera. En fin, creo que sí era importante.</p>
                
                <p>Por muchos años, quien ha llevado la batuta como pintora estandarte del arte mexicano había sido, sin duda, Frida Kahlo (que, vamos, hasta tiene su biopic). No así Remedios Varo, quien hoy por hoy ha sido redescubierta y revalorada. Y que, vamos, sinceramente, es infinitamente mejor pintora que Frida. Sin embargo, esta no es tan famosa; digamos que más por una cuestión de mercadeo y comercialización que otra cosa. Pero, sin duda, incluso la propuesta estética de Remedios (que raya en lo surrealista) es mucho más interesante que los autorretratos repetitivos de Kahlo.</p>
                
                <p>Luego descubrí también que en esta carrera hay otra materia que se lleva después y que se llama "narrativa transmedia". Una es taller de narrativa y la otra es igual, pero con el "trans" y el "media". Por lo visto, no eligió mejor nombre de vanguardia, ya que hoy actualmente todo es "trans": transgénico, transexual, transgresor. En fin, todo lo "trans" es cool (menos las grasas trans, esas no tanto, pero todo lo demás sí).</p>
                
                <p>La finalidad de la narrativa transmedia, versus la narrativa tradicional, consiste en romper los formatos, no así las reglas de la narrativa. Ejemplo: empezar por el final, hacer varios nudos y después el preludio, y finalmente el inicio con un universo alterno. No. La narrativa transmedia trata de formatos. De video, por ejemplo, y no me refiero al mp4, avi o mpeg; me refiero a los formatos de plataformas digitales. Ya que estos chicos estudiaban audiovisuales, el asunto va encaminado a contar una historia de forma diferente en diferentes formatos y para diferentes plataformas.</p>
                
                <p>Como podría ser la historia de Cenicienta en un formato televisivo, a modo de telenovela, y que por ende, al tener muchos capítulos por tradición, sería larga. Una serie, en contraparte, haría uso de la economía narrativa y reduciría los diálogos al máximo en pro de dejar al lenguaje audiovisual hablar. Una película lo haría igualmente, pero en máximo dos horas. Pero incluso esa misma historia podría volverse foto, o volverse pintura, y solo tendría un plano que a su vez jugaría con las dimensiones y la sintaxis de la imagen. Repito: en pro de la historia.</p>

                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/ciencia-inutil-o-el-alquimista.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="Ciencia inútil o el alquimista de Remedios Varo">
                    <figcaption>"Ciencia inútil o el alquimista", de Remedios Varo, chispa de una paradoja digital.</figcaption>
                </figure>
                
                <p>Recuerdo que ese día llevaba mi cámara y uno de los chicos tenía un aspecto tan cansado y curioso. Recuerdo haber visto la imagen de fondo: uno de los cuadros de Remedios Varo, por supuesto, titulado "Ciencia inútil o el alquimista" (portada de uno de los libros de física en secundaria, lo recuerdo perfecto). Fue entonces que surgió en mi mente una paradoja digital. Llegando a casa, prendí el ordenador, inspirado, abrí un editor de imágenes y empecé a trabajar en esta apropiación que parte de un movimiento actualmente llamado postmodernismo.</p>
                
                <p>La narrativa transmedia nos dice que toda historia merece ser contada en diferentes formatos y en todas adquirirá un tono diferente, de mayor o menor dimensión. Lo interesante de esto es que también una historia podría ser contada en partes y en diferentes formatos. Esto es: que una imagen nos puede dar el inicio de la historia, un texto seguir con la misma y finalizarla con un video que emita la resolución. Una historia en partes, pero todas las partes se contarían desde diversas plataformas.</p>
                
                <p>Lo vemos actualmente con el citado postmodernismo. Sin duda, una buena época para hacer una retrospectiva de todo lo que se ha creado, reinterpretarlo y apropiarlo para convertirlo en una nueva obra. Algo que, sin duda, le sentará fatal a la creatividad de los años venideros, ya que si solo nos enfocamos en lo que ya se hizo, no habrá pie para la innovación; por ende, habrá un estancamiento creativo sin precedentes.</p>
                
                <blockquote>
                    "Si tuviéramos que culpar a alguien, podríamos empezar con Warhol y Duchamp, que sin duda propiciaron que actualmente todo sea una reinterpretación."
                </blockquote>
                
                <p>Justamente en las redes sociales, si analizamos un poco con detenimiento, esta generación de influencers está influenciada a su vez, mayormente, por la cultura Disney. Y aunque muchos artistas hacen reinterpretaciones más oscuras de estas historias rosas, en donde vemos una doble cara de la sociedad "utópicamente feliz" y "la magia Disney", es un poco preocupante que una gran mayoría de ilustradores, pintores y artistas visuales estén influenciados principalmente por la cultura de personajes animados. Que claro, no está mal; lo que preocupa es que Disney sea la fuente principal de inspiración de millones de artistas postmodernos.</p>
                
                <p>De igual forma, el posmodernismo también hace uso de la narrativa transmedia, ya que al tomar la obra de otro y transformarla en otra cosa diferente, hace que la historia cambie, así como el contexto y el mensaje. Hay creatividad, hay originalidad, pero también, muchas de las veces, las obras son sumamente mediocres.</p>
                
                <p>Hace unos años, una artista que se hacía llamar de vanguardia puso de moda un término que no resonaba en el mundo del arte, al menos tan fuerte como lo fue después: "apropiación". En el 2014, la pintora Karla de Lara hizo una serie de pinturas sobre Spider-Man (universo de caricaturas, nuevamente). Pero lo que ella hizo fue tomar una imagen de un pintor neoyorquino famoso, un cuadro sobre el Hombre Araña, y por medio de un ordenador y proyector, proyectarlo sobre un lienzo y así empezar a pintar el cuadro. Esto podría ser más una reproducción artesanal que otra cosa.</p>

                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/mushasho-cansado-final-+-marco-blog1.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="Paradoja digital y apropiación">
                    <figcaption>La paradoja digital: reinterpretando lo clásico a través de la lente contemporánea.</figcaption>
                </figure>
                
                <p>Pero entonces, luego de la avalancha de críticas sobre su legitimidad como autora, se defendió de forma magistral y, en una jugada maestra (me imagino que diseñada por sus asesores), llamó a su trabajo una "apropiación" de la obra. Finalmente, en un giro inesperado, salió bien librada y no pasó a mayores. Luego de esto, este término se volvió famoso. Ella también, pero su fama solo duró 5 minutos. Bueno, no, creo que sí ha sobrevivido a la fama de ese incidente, pero si lo analizamos un poco, su fama se debe más a este incidente que a su talento u originalidad. Igual lo hiciera Duchamp con el mingitorio, o Warhol con las cajas de jabón.</p>
                
                <p>Finalmente, que el movimiento esté desvirtuado o trastocado no significa que esté próximo a desaparecer. Todos tenemos esa influencia bien presente de los grandes artistas que marcaron nuestra infancia, nuestra adolescencia y madurez, y que serán la cita de la cita de la cita. El caso más reciente es el de Fabián Cháirez con su Zapata andrógino, que carece de rigor técnico, pero solo por implementar los elementos correctos (por no decir una fórmula probada), el hombre pasó a la historia del arte moderno mexicano.</p>
                
                <p>Lo vimos también con Gabriel Orozco y su "Oroxxo", que fue un parteaguas en el mundo de la instalación. Volvemos otra vez a integrar elementos de nuestra cotidianidad y hacerlo arte. Sin duda, este trabajo tenía un gran discurso que rompió en su momento con las narrativas de las instalaciones tradicionales. Aunque, si hablamos de talento, él ni siquiera llevó o acomodó las galletitas en su tienda de arte. Pero al tener la idea, y después gente que la ejecutara, se convirtió en un discurso transmedia. Si es arte o no, está claro que hubo un statement. Y el arte vive de eso: de declaraciones o negaciones, tesis que podrían o no ser ciertas, pero que finalmente no importa, ya que el espectador pone punto final en esta historia, cerrando el ciclo de la narrativa con lo que él da por entendido en la obra.</p>

                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/mushasho-cansado-paradoja-blog.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="Reflexión sobre el arte y el espectador">
                    <figcaption>El espectador pone el punto final: cerrando el ciclo de la narrativa.</figcaption>
                </figure>
                
                <p>Aunque el postmodernismo esté lejos de desaparecer, estoy seguro de que la tecnología hará posible la invención de nuevas historias que rompan la narrativa tradicional. Esto también quiere decir que podríamos reinventar las narrativas de las obras originales, deformarlas o moldearlas las veces que sean necesarias hasta que el origen sea tan deslucido que sea imposible reconocer su procedencia.</p>
                
                <p style="font-size: 1.25rem; font-weight: 600; color: #121212; margin-top: 3rem; border-top: 1px solid #e2e2e2; padding-top: 2rem;">
                    El lenguaje en el arte es infinito. Y así como una pintura puede inspirar una historia, o una pieza musical puede inspirar imágenes que estén tan lejos de la original que de por completo algo nuevo, único y sorprendente; solo tenemos que romper las reglas de la narrativa, del postmodernismo y de la transmedia. Y si vamos un poco más allá, romper los límites de nuestro propio talento en pro de una historia más original: la nuestra, por supuesto.
                </p>
            </article>

