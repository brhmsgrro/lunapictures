          <p class="text-justify">Finalmente que el movimiento este desvirtuado o trastocado no significa que este próximo a desaparecer, todos tenemos esa influencia bien presente de los grandes artistas que marcaron nuestra infancia, nuestra adolescencia y madurez, y que serán la cita de la cita de la cita, el caso mas reciente es el de Fabian Chairez con su zapata andrógino, que carece de rigor técnico pero solo por implementar los elementos correctos  (por no decir una formula probada) el hombre paso a la historia del arte moderno mexicano. </p>

          <p class="text-justify">Lo vimos también con Gabriel Orozco y su oroxxo, que fue un parteaguas en el mundo de la instalación, volvemos otra vez a integrar elementos de nuestra cotidianidad y hacerlo arte, sin duda este trabajo tenia un gran discurso que rompió en su momento con las narrativas de las instalaciones tradicionales, aunque si hablamos de talento, el ni siquiera llevo u acomodo las galletitas en su tienda arte, pero al tener la idea, y después gente que la ejecutara se convirtió en un discurso transmedia, si es arte o no, esta claro que hubo un statement y el arte vive de eso, de declaraciones o negaciones, tesis que podrían o no ser ciertas, pero que finalmente no importa, ya que el espectador pone punto final en esta historia, cerrando el ciclo de la narrativa, con lo que el da por entendido en la obra. </p>
 
          <p class="text-justify">Aunque el postmodernismo este lejos de desaparecer, estoy seguro que la tecnología  hará posible la invención de nuevas historias, que rompan la narrativa tradicional, esto también quiere decir que podríamos reinventar las narrativas de las obras originales, deformarlas o moldearlas las veces que sean necesaria hasta que el origen sea tan deslucidado que sea imposible reconocer su procedencia, el lenguaje en el arte es infinito y así como una pintura puede inspirar una historia, o una pieza musical puede inspirar imágenes que estén tan lejos de la original que de por completo algo nuevo único y sorprendente solo tenemos que romper las reglas de la narrativa, del postmodernismo y de la transmedia y si vamos un poco más allá romper los limites de nuestro propio talento en pro de una historia mas original, la nuestra por supuesto. </p>
					
