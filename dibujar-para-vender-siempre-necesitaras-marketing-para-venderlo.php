<p class="text-justify">Todos los que seguimos la música pop hemos visto gente sin ningún talento para cantar y bailar y que de hecho han despuntado en sus carreras y gente muy talentosa con voces excepcionales que no pasan de cualquier “canta bar”. ¿Qué pasa entonces? ¿será que estrategia mata talento? o en este caso ¿la falta talento se pude disimular con un buen marketing? O ¿es que hay gente que sabe vender muy bien lo que vende? bueno sí y no, veremos.</p>

<p class="text-justify">Lo que talento no da, ensayo no presta; todos a lo largo de nuestras vidas vamos desarrollando y adquiriendo habilidades con las cuales nos sentimos más cómodos u óptimos. Estos talentos están ahí, y no sabemos cómo ni porque, pero lo tenemos venimos con ellos, luego crecemos y nos damos cuenta de que algunos “talentos” no son para nada útiles y también descubrimos (a veces tardíamente) que tenemos talentos que no sabíamos que teníamos. Personalmente he conocido gente buenísima para el balompié y les he dicho: “caramba tenes futuro en esto” y ellos dicen: “no, la verdad no me gusta tanto” y se van por otro camino. He conocido gente que es buenísima para los efectos de video que finalmente dejan la edición para correr detrás de un balón y en lo cual uno cree que no son lo suficientemente buenos, pero les apasiona. Y sí con el tiempo y dedicación serán mejor de lo que fueron ayer, pero los talentos naturales fueron otros en principio. Finalmente, uno se da cuenta de qué es de lo que le dará a uno para vivir.</p>

<p class="text-justify">Les daré un ejemplo; pero remontémonos unos años más atrás en la infancia de este narrador; cuando cursaba la educación primaria, recuerdo que en 3 o 4to curso más o menos, se nos pidió escribir una historia, yo escribí una que realmente era un plagio, (aunque la adapte a otro contexto) de una historia que había visto en televisión, recuerdo que la leí en voz alta ante el grupo y a todos les gusto… uno de los compañeros me descubrió y me delato pero entonces lo negué y la profesora me creyó. Después en la secundaria paso lo mismo varias veces, los maestros leían mis historias y me pedían que las leyera en voz alta, me paso en el bachillerato donde gane un concurso incluso, (del salón, aun así, fue la mejor historia por votación, digo cuenta ¿no?) en clases de actuación paso lo mismo con una historia que se adaptó para un cortometraje en una video cámara, incluso llegue a ganar una beca universitaria para estudiar en una escuela privada gracias a escribir.  </p>

<p class="text-justify">En fin la escritura siempre se me ha dado, ha sido muy fácil para mí, solo me siento y empiezo a escribir, si lo hago bien o mal, bueno ese es otro tema, pero el punto es que es un don que tenía desde pequeño, no sé cómo pero ahí ha estado, aunque sinceramente nunca lo he desarrollado, digo podría haber estudiado alguna licenciatura en filosofía y letras pero es que jamás me vi como un Juan Rulfo o un Juan José Arreola;  además siempre he pensado que la escritura (el oficio) es más para los burgueses, y yo prefiero vender hamburguesas antes que ser burgués.</p>

<p class="text-justify">De cualquier forma, el talento está en uno, solo hay que investigar cual es y/o buscarlo. Pero bueno ya me estoy desviando demasiado del punto principal, algo para lo que no soy bueno y que nunca me ha gustado es dibujar; también cuando cursaba el colegio secundario teníamos clases de educación artística, estas clases su único objetivo era despertar la sensibilidad de los alumnos más allá de formar artistas. Recuerdo que como parte del curso hicimos unas acuarelas en papel cascaron de huevo. El profesor me felicito en algunas y me escribió uno de esos mensajes alentadores, “sigue dibujando tú puedes”  la verdad nunca me gustó dibujar, me desespera, no encuentro relajación en ello, ideas para plasmar tengo bastantes pero digamos que lo que me da un poco de pereza es todo el proceso de bocetar y borrar, más allá de que cuando te concentras se te pasa el tiempo y después te das cuenta de que aun tienes un montón de tareas pendientes, me frustra un poco.  Es casi la misma sensación que obtengo con las redes sociales, digo me gustan, pero finalmente pierdo horas absorto en ver puras tonterías (que me hacer reír, pero tonterías finalmente).</p>

<p class="text-justify">Pero bien, muchas veces lo he tenido que hacer, dibujar. Dicen que el cerebro es más complejo una vez que empieza a pintar, se plantea resolver problemas y por ende en la vida real te vuelves más efectivo para resolverlos, tal vez eso no lo había entendido, pero creo que es cierto ya que la idea principal de dibujar es que si quieres transmitir una idea lo más fácil es dibujarla (o escribirla), y si lo pensamos un poco así ha sido desde la prehistoria, con esas pinturas rupestres por ejemplo, ¿qué querían decir realmente nuestros ancestros? Contarnos una historia sobre la caza, o talvez el pintor solo quería plasmar su día a día como un diario para no olvidar como fue, o es que no tenían nada mejor que hacer que pintar, como sea, el chiste es que si sabemos eso sobre ellos (o lo suponemos) y su estilo de vida es por medio de los dibujos que quedaron ahí plasmados.</p>

<p class="text-justify">En fin hace unos días mientras ordenaba mis archivos encontré estas pinturas entre mis cosas, vinieron a mi todos estos recuerdos y me decidí pintar la misma imagen pero ahora en Photoshop, algo que también esta muy desvalorado es el diseño gráfico, caramba la gente ignora el potencial que puede tener un diseñador grafico por ejemplo en el mundo editorial lo es todo, pero bueno ese tema lo dejaremos para después, finalmente este fue el resultado, ahora con pintura digital, sigue estando carente de talento pero en su momento lo hice por obligación para pasar un curso ahora para superar un reto personal, y creo que lo logre. 
 </p>

