            <article class="editorial-body">
                <p class="drop-cap">No importa a qué te dediques, siempre necesitarás marketing para venderlo. Una máxima que leí, sinceramente no recuerdo en dónde, pero que además hoy por hoy sería muy difícil comprobar su procedencia original. Pudo haber sido un retweet del retweet, quién sabe… hasta que finalmente apareció en mi muro de noticias, tal vez en Instagram, tal vez en Facebook. En fin, nunca lo sabremos.</p> 

                <p>El punto es que siempre se necesitará saber vender para vender lo que hacemos. En ocasiones esa es la principal limitante de los emprendedores: pueden ser los mejores a la hora de fabricar pasteles, pero no ser los mejores promotores de su propio trabajo. Y cuando uno empieza en el negocio, lo que menos hay es dinero para pagar a un buen mercadólogo (error que debería corregirse con el tiempo) y menos para hacer un plan de marketing.</p>
                
                <blockquote>
                    "Lo que el talento no da, el ensayo no presta. Todos a lo largo de nuestras vidas vamos desarrollando y adquiriendo habilidades con las cuales nos sentimos más cómodos u óptimos."
                </blockquote>
                
                <p>Y es aquí donde nos desviaremos un poco, correlacionándolo a otro tópico más: el talento. El talento puede ser nato o adquirido, claro está, pero el talento está o no está. Todos los que seguimos la música pop hemos visto gente sin ningún talento para cantar y bailar que de hecho han despuntado en sus carreras, y gente muy talentosa con voces excepcionales que no pasan de cualquier "canta bar". ¿Qué pasa entonces? ¿Será que la estrategia mata al talento? ¿O la falta de talento se puede disimular con un buen marketing?</p>
                
                <p>Estos talentos están ahí, y no sabemos cómo ni por qué, pero los tenemos; venimos con ellos. Luego crecemos y nos damos cuenta de que algunos "talentos" no son para nada útiles, y también descubrimos (a veces tardíamente) que tenemos talentos que no sabíamos que teníamos. Personalmente he conocido gente buenísima para el balompié y les he dicho: "Caramba, tienes futuro en esto", y ellos dicen: "No, la verdad no me gusta tanto", y se van por otro camino. He conocido gente que es buenísima para los efectos de video que finalmente dejan la edición para correr detrás de un balón. Y sí, con el tiempo y dedicación serán mejor de lo que fueron ayer, pero los talentos naturales fueron otros en principio.</p>
                
                <h3>El don de la escritura</h3>
                
                <p>Les daré un ejemplo, pero remontémonos unos años más atrás en la infancia de este narrador. Cuando cursaba la educación primaria, recuerdo que en 3° o 4° curso, más o menos, se nos pidió escribir una historia. Yo escribí una que realmente era un plagio (aunque la adapté a otro contexto) de una historia que había visto en televisión. La leí en voz alta ante el grupo y a todos les gustó. Uno de los compañeros me descubrió y me delató, pero entonces lo negué y la profesora me creyó.</p>
                
                <p>Después, en la secundaria, pasó lo mismo varias veces: los maestros leían mis historias y me pedían que las leyera en voz alta. Me pasó en el bachillerato, donde gané un concurso incluso (del salón, aun así, fue la mejor historia por votación, ¿cuenta, no?). En clases de actuación pasó lo mismo con una historia que se adaptó para un cortometraje en una videocámara. Incluso llegué a ganar una beca universitaria para estudiar en una escuela privada gracias a escribir.</p>
                
                <p>En fin, la escritura siempre se me ha dado, ha sido muy fácil para mí. Solo me siento y empiezo a escribir. Si lo hago bien o mal, bueno, ese es otro tema. Pero el punto es que es un don que tenía desde pequeño. No sé cómo, pero ahí ha estado, aunque sinceramente nunca lo he desarrollado. Podría haber estudiado alguna licenciatura en filosofía y letras, pero es que jamás me vi como un Juan Rulfo o un Juan José Arreola. Además, siempre he pensado que la escritura (el oficio) es más para los burgueses, y yo prefiero vender hamburguesas antes que ser burgués.</p>
                
                <h3>La frustración del dibujo</h3>
                
                <p>De cualquier forma, el talento está en uno, solo hay que investigar cuál es y/o buscarlo. Pero bueno, ya me estoy desviando demasiado del punto principal. Algo para lo que no soy bueno y que nunca me ha gustado es dibujar. Cuando cursaba el colegio secundario teníamos clases de educación artística; estas clases tenían como único objetivo despertar la sensibilidad de los alumnos, más allá de formar artistas. Recuerdo que como parte del curso hicimos unas acuarelas en papel cascarón de huevo. El profesor me felicitó en algunas y me escribió uno de esos mensajes alentadores: "Sigue dibujando, tú puedes".</p>
                
                <p>La verdad, nunca me gustó dibujar. Me desespera, no encuentro relajación en ello. Ideas para plasmar tengo bastantes, pero digamos que lo que me da un poco de pereza es todo el proceso de bocetar y borrar. Más allá de que cuando te concentras se te pasa el tiempo y después te das cuenta de que aún tienes un montón de tareas pendientes; me frustra un poco. Es casi la misma sensación que obtengo con las redes sociales: digo, me gustan, pero finalmente pierdo horas absorto en ver puras tonterías (que me hacen reír, pero tonterías finalmente).</p>
                
                <p>Pero bien, muchas veces lo he tenido que hacer: dibujar. Dicen que el cerebro es más complejo una vez que empieza a pintar; se plantea resolver problemas y, por ende, en la vida real te vuelves más efectivo para resolverlos. Tal vez eso no lo había entendido, pero creo que es cierto, ya que la idea principal de dibujar es que si quieres transmitir una idea, lo más fácil es dibujarla (o escribirla).</p>
                
                <p>Y si lo pensamos un poco, así ha sido desde la prehistoria, con esas pinturas rupestres, por ejemplo. ¿Qué querían decir realmente nuestros ancestros? ¿Contarnos una historia sobre la caza? ¿O tal vez el pintor solo quería plasmar su día a día como un diario para no olvidar cómo fue? ¿O es que no tenían nada mejor que hacer que pintar? Como sea, el chiste es que si sabemos eso sobre ellos (o lo suponemos), y su estilo de vida, es por medio de los dibujos que quedaron ahí plasmados.</p>
                
                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/la-mujer-en-el-rio-blog.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="La mujer en el río - versión original">
                    <figcaption>La mujer en el río — versión original en acuarela sobre papel cascarón de huevo.</figcaption>
                </figure>
                
                <p>En fin, hace unos días, mientras ordenaba mis archivos, encontré estas pinturas entre mis cosas. Vinieron a mí todos estos recuerdos y me decidí a pintar la misma imagen, pero ahora en Photoshop. Algo que también está muy desvalorado es el diseño gráfico; caramba, la gente ignora el potencial que puede tener un diseñador gráfico. Por ejemplo, en el mundo editorial lo es todo. Pero bueno, ese tema lo dejaremos para después.</p>
                
                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/la-mujer-en-el-rio-2-blog.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="La mujer en el río - versión digital en Photoshop">
                    <figcaption>La mujer en el río — recreación digital en Photoshop. Un reto personal superado.</figcaption>
                </figure>
                
                <p>Finalmente, este fue el resultado: ahora con pintura digital. Sigue estando carente de talento, pero en su momento lo hice por obligación para pasar un curso; ahora, para superar un reto personal. Y creo que lo logré.</p>

                <h3>La habilidad clave del emprendedor</h3>
                
                <p>Para terminar, la conclusión sería esta: un emprendedor también es un talento con el que se nace y que también se puede adquirir. Personalmente, muchas veces me he sentido frustrado por no ser tan buen "comerciante" como quisiera, pero en el mundo del emprendedurismo o captas que este juego es así, o lo dejas de jugar. Ensayo y error. De los errores aprendes.</p>
                
                <p>Pero digamos que para saber si eres un emprendedor o no, la pregunta clave sería: <mark>¿estás conforme con lo que tienes?</mark> Creo que tú sabes cuál es la respuesta correcta.</p>
                
                <p>Para ser un mejor emprendedor, al igual que escritor o dibujante, todo radica en encontrar las habilidades clave. Una habilidad clave para dibujar es la paciencia, por ejemplo: no sabes dibujar, primero desarrolla paciencia. Para emprender sería saber vender. Pero, ¿cómo puedo aprender eso? ¿Cómo puedo aprender a vender?</p>
                
                <p>Bueno, observa a tu alrededor y ve el diseño gráfico de todo lo que hay a tu alrededor. Todo tiene imágenes. ¿Qué te dicen esas imágenes? Las imágenes siempre han acompañado al ser humano. Si tienes un negocio y no tienes imágenes porque no hay presupuesto para armarlas, pues dibújalas. Dibuja tus ideas y plásmalas. Dibuja para entender cómo sería esa remodelación en tu casa. Dibuja para diseñar el food truck que quieres mandar a construir.</p>
                
                <p style="font-size: 1.25rem; font-weight: 600; color: #121212; margin-top: 3rem; border-top: 1px solid #e2e2e2; padding-top: 2rem;">
                    Pero sobre todo, dibuja para vender. Tengas o no tengas talento, el tiempo se encargará de eso, no os preocupéis. Dibuja para aprender a vender. Y solo sabrás si lo estás haciendo bien cuando la gente entienda tus ideas sin necesidad de explicarlas.
                </p>
            </article>

