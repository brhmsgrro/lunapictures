$(document).ready(function(){

  $('#contactoss').on('submit', function(e){
    e.preventDefault();

    let nombre = $('#name').val().trim();
    let email = $('#email').val().trim();
    let mensaje = $('#message').val().trim();

    // Validaciones
    if(nombre === ""){
      alert("Debes agregar el nombre");
      return;
    }

    if(email === ""){
      alert("Debes agregar tu correo");
      return;
    }

    // Validación real de email
    let regex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if(!regex.test(email)){
      alert("Correo no válido");
      return;
    }

    if(mensaje === ""){
      alert("Debes agregar un mensaje");
      return;
    }

    // Desactivar botón
    $('#btn-contacto').prop('disabled', true).text('Enviando...');

    $.ajax({
      type: "POST",
      url: "enviar-contacto.php",
      data: $(this).serialize(),
      success: function(res){

        if(res.trim() === "1"){
          gtag('event','contacto',{
event_category:'ventas',
event_label:'formulario'
});
          alert("Gracias 🙌 en breve te contactamos");
          $('#contactoss')[0].reset();
        }else{
          alert("Error del servidor: " + res);
        }

        $('#btn-contacto').prop('disabled', false).text('Enviar');
      },
      error: function(){
        alert("Error de conexión 😓");
        $('#btn-contacto').prop('disabled', false).text('Enviar');
      }
    });

  });

});
</script>

  
 
