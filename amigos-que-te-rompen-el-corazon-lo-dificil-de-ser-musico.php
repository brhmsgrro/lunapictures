<h3></h3></p>

<p class="text-justify">No sé si sería por el alcohol, pero nunca me había percatado que Jess siempre se relacionaba con personas densas, ese tipo de personas que siempre tienen problemas en su vida. Digo todos tenemos problemas, pero me refiero a ese tipo de personas toxicas que siempre se están quejando de lo mal que les va en la vida, pero que en el fondo son ellos mismos los responsables de sus malas decisiones, en fin, o talvez si lo había notado, pero nunca me había tocado convivir con sus amigos. De vez en cuando volteaba a verla; seguía sin despegársele a mi primo, él es muy guapo la verdad, pero se supone que ella estaba aquí por mi cumpleaños, y se pasó toda la noche resbalándosele a él. Repito, no sé si era la botella y media de alcohol que para ese entonces ya me había bebido pero nunca había notado esa personalidad en Jessica, a ella la conocí en la escuela de música y ella al revés mío había hecho solo el propedéutico y luego deserto, alguna vez me confesó que había entrado a la licenciatura porque le gustaban los Rockeros, pero que la música no tanto, aun no me explico como paso los exámenes de admisión que sí son muy difíciles, supongo que ritmo sí tiene, eso lo comprobé después de verla bailar reggaetón con mi primo. Mientras bailaba retorciéndosele a mi familiar recordé mis aventuras con ella y me sorprendió de cómo había seguido la amistad con ella pesé haber dejado la carrera. </p>

<p class="text-justify">De repente en el móvil recibí un mensaje del número de Sofia, mi amiga de la licenciatura de administración: “lo siento no podré ir, el bebe tiene reflujo y estoy muerta de cansancio espero me disculpes” ....  - Macandy, ¿quieres que ya sirva la comida o esperamos a que lleguen los demás? -  se acercó mi madre - sí, está bien- respondí. -  Pero Sofia aun no llega ¿no esperaras a Sofí? - me preguntó, - Ella no vendrá- Oh!, respondió mi mamá; creo que noto mi cara de desconcierto porque no dijo nada más y se fue.  Mientras estudiaba la licenciatura en administración, la escuela había organizado un viaje cultural universitario al famoso festival cervantino, éramos: Sofia, José Luis su novio, mi novio de ese entonces (que la verdad no importa el nombre) y yo. teníamos poco de haber ingresado a la carrera y todos nos caímos muy bien. Al final del día todos estábamos eufóricos, ebrios y afónicos ya que pasamos la mayor parte del viaje gritando y bebiendo, ambos chicos se alejaron un momento porque mi novio ya no podía más y se puso a vomitar, como las calles de esa ciudad son muy estrechas nos sentamos en la fuente de una acera a esperarlos. La noche se puso sola y silenciosa, entonces Sofia tal vez por el alcohol, empezó a platicarme sobre su relación y me contaba que su novio era muy duro con ella que la maltrataba psicológicamente pero que yo la hacía sentir como debía ser una mujer segura de sí misma y que en el fondo quería ser como yo, me admiraba, yo no entendía porque, en fin se quebró, empezó a llorar y yo trate de consolarla ya más calmada me dijo que no sabía porque todos  los hombres eran unos idiotas que no sabían escucharnos etc… de un de repente se quedó en silencio mirando mis ojos profundamente, bajo su mirada a mis labios y su cara se acercó a mi rostro .. me besó. En ese instante yo no supe que hacer solo recuerdo que entrecerré mis ojos y me preguntaba: ¿Soy lesbiana? qué estaba pasando, me cuestioné. Un montón de cosas pasaron en mi cabeza, más cosas de los segundos que duro ese beso, se alejó de mí ... y solo sonrió… yo con cara de ¿WHAT? …  de la nada apareció José Luis - Vámonos ya Sofia - dijo él. Yo no lo había sentido llegar. ¿Nos vio? Me pregunté, nunca lo supe, pero todo el viaje de regreso Jos Luis estuvo muy frio conmigo a penas si me dirigió la palabra y evitaba el contacto visual conmigo. </p></br>


<h3></h3></p>

<p class="text-justify">La comida no me supo, Jess no paraba de querer ser el centro de atención, y hacia bromas para que todos la escucháramos.  Yo por mi parte aun recordando aquel viaje al cervantino después de haber recibido el mensaje de Sofia pensaba en lo curioso  que era mi amistad con ella y de como ésta, se había mantenido intacta a pesar de aquel incidente, con los meses luego de ese viaje me cambie de carrera ella terminó la licenciatura en administración, se casó con José Luis tuvieron un hijo y habíamos mantenido el contacto todo este tiempo regularmente pero ya teníamos más de un año de no vernos porque me había volcado en mis estudios finales, tenía muchas ganas de verla. sin embargo, no llegó, siempre supuse que su esposo se sentía incomodo con nuestra amistad, bueno después de ese beso si es que nos vio, porque antes nos llevamos muy bien. Pero siempre supe que eso no significó nada para ella, en realidad tampoco para mí, las mujeres podemos manejar ese tipo de situaciones muy bien, no tanto así los hombres; mi mejor amigo gay que en estos momentos come junto a mi como si no hubiera mañana, vivió algo así con su mejor amigo, literal vivió la historia de la película “y tu mama también” se los juro. Es más Alfonso Cuarón se inspiró en su historia para rodar esa película, con todo y el baile con la canción del buki, lo juro por Cristian Dior, bueno esa es la broma que siempre cuento enfrente de él, cuando la situación viene al caso. Lo que supe después de ese día es que yo era bisexual, y que podía estar con otras chicas sin ningún problema, eso sumo puntos en mis relaciones posteriores, ya que a ninguno de mis novios le parecía mal. Bueno debo aclarar que todos fueron músicos, en fin, músicos que les puedo decir.  
</p></br>

<p class="text-justify">En mi celular aparecía una notificación mas; era mi profesor de piano que se había convertido en un amigo para mí, durante la carrera. El profe Gerardo al que había invitado también, se había mostrado entusiasmado por asistir y ver la presentación en mi cumpleaños, él personalmente me ayudo a preparar las canciones que tocaría ese día; aun así, tampoco llegó. Casi estoy segura que su esposa no le había dado permiso así sin más, ya que tampoco le caía bien a la esposa de mi maestro, que les puedo decir, caer mal es mi verdadero talento. Supongo que fue de esas veces que te dicen “si quieres ir. ve… sin problemas” pero sabemos que lo que en realidad quieren decir es “yo podría acompañarte, pero no quiero ir. Y si vas solo, vete. pero tendremos problemas por esto, oh sí” a pesar de no haberse presentado me había escrito unas palabras por mis redes sociales, diciendo lo orgulloso que estaba de mí que lamentaba no estar conmigo que era una causa de fuerza mayor. pero que yo era una chica super talentosa y todo lo que hiciera me saldría bien. etc. etc.., finalmente agradecí al universo que no estuviera aquí para comprobar lo contrario, ironicé.  </p>


