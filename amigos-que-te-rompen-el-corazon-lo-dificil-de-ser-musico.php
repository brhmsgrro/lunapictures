          <p class="text-justify">De fondo se escucha el último disco de james Blake en el play list de aquel bar, de repente cambia el track y en esta nueva canción la letra en ingles dice algo más o menos así… “al final fueron amigos los que me rompieron el corazón” … entonces recordé una particular presentación que tuve en ese mismo bar unos meses atrás. </p>

<p class="text-justify">Estaba sentada en este mismo lugar, pero con un teclado enfrente mío, había acordado con el dueño, realizar una presentación de teclado gratuita, eso con motivo de mi cumpleaños, pero al mismo tiempo serviría para celebrar la conclusión de mi licenciatura en música, luego de desertar de la carrera en administración de empresas (solo curse dos semestres para ser exacta) les había dicho a mis padres, lo siento no puedo más, y renuncié. Ahora me doy de topes ya que pude haber hecho ambas licenciaturas, pero no, en aquel entonces con la efervescencia de la juventud y los estúpidos ímpetus de querer cambiar el mundo a través del arte, me lancé a la aventura de estudiar solamente música. Ahora sé que en esta vida solo necesitas aprender dos cosas nada más, solo dos cosas; la primera es a quererte, valorarte etc.… y la segunda aprender a usar excel; pero esa es otra historia. Volviendo a mi recital había planeado algo muy íntimo ya saben familia, “novios” (es broma, solo un novio), amigos, etc. Quería que la gente más cercana a mi estuviera conmigo en ese momento tan mágico en el que se unían mi cumpleaños y la conclusión de mis estudios, curiosamente. Que mejor regalo que ese pensé. Había llamado a todo mundo y los había conminado a mi evento, todos habían aceptados encantados. </p>

 <p class="text-justify">Mi mejor amigo gay, Sergio, que en realidad tenía poco de conocer -pero que es muy gay y por eso es el mejor- estaba con la cámara del celular grabando. Yo pasmada con las manos sobre las teclas del instrumento sin saber que hacer, — ¿Macandy? ¿Todo bien? — me pregunto. — No recuerdo nada - le comenté. ¡No podía creerlo, estaba sentada al teclado la gente esperando a que empezara y mi cabeza estaba en blanco, fue un black out total, no recordaba nada!  - Olvidé todo!! – le dije. ¿Quieres que paremos? Me comento …  Yo simplemente No recordaba nada; no recordaba la letra, no recordaba los acordes, entre en shock.  -Talvez has bebido demasiado. – me dijo él - ¡Solo tome dos copas de tinto! ¡Es mi cumpleaños! - Le dije. - En realidad fueron cuatro copas, cariño…  - bueno y eso que! – respondí molesta. - Amy Winehouse cantaba hasta drogada, bueno hasta chuy de REIK que es menos famoso y talentoso se sube borracho al escenario y pueden con el paquete, le increpe susurrando para que los presentes no se dieran cuenta de lo que estaba pasando -bueno tú no eres ellos - me dijo - además el talento cuenta - remató, …yo lo voltee a ver con una mirada fulminante; – el talento para beber y subir a interpretar también cuenta cariño ese también es un talento, quise decir … — dijo mi amigo tratando de componer lo que acaba de decir; mi cara de incertidumbre no daba crédito a sus palabras.</p></br>

<p class="text-justify">Mi set list era muy simple primero empezaría con el canon de Pachabel; para que se vieran los años de estudios en la maldita escuela de música, seguidos por dos canciones populares una de regional mexicano para toda “la banda” y una de Madonna; porque en el fondo creo que soy 10% lesbiana, entonces orgullo y esas cosas. - Bueno concéntrate - me dijo. Debo aclarar que a Sergio tenía pocos meses de conocerlo es mas no pensé que fuera a estar presente y menos grabando mi cumpleaños. Después volteé a ver a todos los presentes, y ninguno parecía percatarse de lo que pasaba, digo finalmente era un bar, había un silencio, pero no absoluto, había más gente, pero a nadie parecía importarle.</p>
Como pude recordé algo de la canción popular regional y empecé a tocar y cantar (descuadrada y desafinada, pero terminé) al final nadie aplaudió ni nadie se enteró. Solo note que Jesica mi mejor amiga coqueteaba con mi primo al que considero prácticamente mi hermano, la canción que acababa de interpretar la había elegido para ella, porque sabía de su ultimo mal de amores y siempre había considerado que era una chica dulce entonces la había tocado en especial para ella, pero ella seguía coqueteando con mi primo. O sea, de ese “amor de su vida” ni se acordó, porque se supone que esa era su canción, bueno la de ambos, ya saben la típica canción que es el himno de una relación, pero nunca se dio cuenta y después no me dijo nada, entonces asumí que nunca entendió el guiño. Al final me levanté y me dirigí a la mesa donde estaba mi familia me senté junto a ella, y Jessica solo me pregunto si todo estaba bien ... - Sí todo bien - le dije.  Entonces para no ser descortés empecé a hablar con sus invitados, la señora Gladys que se había divorciado recientemente y Alex de no más treinta que había enviudado unos días atrás; yo solo escuchaba estupefacta - ¿Dónde conocieron a Jessica? - les pregunté desconcertada, - Vivimos en el mismo edificio de departamentos que ella- respondió la señora Gladys, - como estos tienen áreas comunes de comedor y patio, pues en ocasiones hemos coincidió y nos caímos bien- remato Alex -  ok- respondí.. – Que curioso Jess no me los había mencionado ¿hace cuanto que se conocen? – pregunte yo. Dos horas antes de venir a mi cumpleaños Jess me había llamado por teléfono preguntándome si no tenía inconveniente en que ella trajera invitados, yo le dije que no había problema pensé que sería algún familiar suyo. - Hace tres días- respondió la señora – nos conocimos esta semana hace tres días.  Yo solo abrí los ojos de par en par sin dar crédito al poco criterio de mi amiga para relacionarse con desconocidos y traerlos a una fiesta intima, una risa nerviosa salió de mi boca, - hay que cosas pues que bien ¿no? - Así es… es que yo recientemente me acabo de divorciar y su esposa murió hace unos días, -nos hacía bien una salidita, feliz cumpleaños, por cierto- me contestaron ellos. Con los ojos abiertos de par en par respondí solo con un descolocado gracias. </p>
