            <article class="editorial-body">
                <p class="drop-cap">De fondo se escuchaba el último disco de James Blake en la playlist de aquel bar. De repente, cambió el track y, en esta nueva canción, la letra en inglés decía algo más o menos así: <em>"al final fueron amigos los que me rompieron el corazón"</em>. Entonces recordé una particular presentación que tuve en ese mismo bar unos meses atrás.</p> 

                <p>Estaba sentada en este mismo lugar, pero con un teclado enfrente. Había acordado con el dueño realizar una presentación gratuita con motivo de mi cumpleaños, pero al mismo tiempo serviría para celebrar la conclusión de mi licenciatura en música, luego de desertar de la carrera en Administración de Empresas (solo cursé dos semestres, para ser exacta). Les había dicho a mis padres: "Lo siento, no puedo más", y renuncié. Ahora me doy de topes, ya que pude haber hecho ambas licenciaturas, pero no. En aquel entonces, con la efervescencia de la juventud y los estúpidos ímpetus de querer cambiar el mundo a través del arte, me lancé a la aventura de estudiar solamente música. Ahora sé que en esta vida solo necesitas aprender dos cosas: la primera es a quererte y valorarte, y la segunda, aprender a usar Excel. Pero esa es otra historia.</p>
                
                <p>Volviendo a mi recital, había planeado algo muy íntimo: ya saben, familia, "novios" (es broma, solo un novio), amigos, etc. Quería que la gente más cercana a mí estuviera conmigo en ese momento tan mágico en el que se unían mi cumpleaños y la conclusión de mis estudios, curiosamente. "Qué mejor regalo que ese", pensé. Había llamado a todo el mundo y los había conminado a mi evento. Todos habían aceptado encantados.</p>
                
                <p>Mi mejor amigo gay, Sergio, que en realidad tenía poco de conocer (pero que es muy gay y por eso es el mejor), estaba con la cámara del celular grabando. Yo, pasmada, con las manos sobre las teclas del instrumento, sin saber qué hacer.</p>
                
                <p>—¿Macandy? ¿Todo bien? —me preguntó.</p>
                <p>—No recuerdo nada —le comenté.</p>
                
                <p>¡No podía creerlo! Estaba sentada al teclado, la gente esperando a que empezara y mi cabeza estaba en blanco. Fue un <em>black out</em> total. No recordaba la letra, no recordaba los acordes, entré en shock.</p>
                
                <p>—Tal vez has bebido demasiado —me dijo él.</p>
                <p>—¡Solo tomé dos copas de tinto! ¡Es mi cumpleaños! —le dije.</p>
                <p>—En realidad fueron cuatro copas, cariño…</p>
                <p>—¡Bueno, y eso qué! —respondí molesta—. Amy Winehouse cantaba hasta drogada. Bueno, hasta Chuy de REIK, que es menos famoso y talentoso, se sube borracho al escenario y pueden con el paquete —le increpé, susurrando para que los presentes no se dieran cuenta de lo que estaba pasando.</p>
                <p>—Bueno, tú no eres ellos —me dijo—. Además, el talento cuenta —remató.</p>
                
                <p>Yo lo voltee a ver con una mirada fulminante. "El talento para beber y subir a interpretar también cuenta, cariño, ese también es un talento", quise decir. Él trató de componer lo que acababa de decir, pero mi cara de incertidumbre no daba crédito a sus palabras.</p>
                
                <p>Mi <em>set list</em> era muy simple: primero empezaría con el Canon de Pachelbel, para que se vieran los años de estudios en la maldita escuela de música, seguidos por dos canciones populares: una de regional mexicano para toda "la banda", y una de Madonna, porque en el fondo creo que soy 10% lesbiana, entonces orgullo y esas cosas.</p>
                
                <p>—Bueno, concéntrate —me dijo.</p>
                
                <p>Debo aclarar que a Sergio tenía pocos meses de conocerlo; es más, no pensé que fuera a estar presente y menos grabando mi cumpleaños. Después voltee a ver a todos los presentes, y ninguno parecía percatarse de lo que pasaba. Digo, finalmente era un bar, había un silencio, pero no absoluto. Había más gente, pero a nadie parecía importarle.</p>
                
                <p>Como pude, recordé algo de la canción popular regional y empecé a tocar y cantar (descuadrada y desafinada, pero terminé). Al final, nadie aplaudió ni nadie se enteró. Solo noté que Jessica, mi mejor amiga, coqueteaba con mi primo, al que considero prácticamente mi hermano. La canción que acababa de interpretar la había elegido para ella, porque sabía de su último mal de amores y siempre había considerado que era una chica dulce. Entonces la había tocado en especial para ella, pero ella seguía coqueteando con mi primo. O sea, de ese "amor de su vida" ni se acordó. Se supone que esa era su canción, bueno, la de ambos; ya saben, la típica canción que es el himno de una relación, pero nunca se dio cuenta. Después no me dijo nada, entonces asumí que nunca entendió el guiño.</p>
                
                <p>Al final me levanté y me dirigí a la mesa donde estaba mi familia. Me senté junto a ella, y Jessica solo me preguntó si todo estaba bien.</p>
                <p>—Sí, todo bien —le dije.</p>
                
                <p>Entonces, para no ser descortés, empecé a hablar con sus invitados: la señora Gladys, que se había divorciado recientemente, y Alex, de no más de treinta, que había enviudado unos días atrás. Yo solo escuchaba estupefacta.</p>
                <p>—¿Dónde conocieron a Jessica? —les pregunté, desconcertada.</p>
                <p>—Vivimos en el mismo edificio de departamentos que ella —respondió la señora Gladys—. Como estos tienen áreas comunes de comedor y patio, pues en ocasiones hemos coincidido y nos caímos bien —remató Alex.</p>
                <p>—Ok —respondí—. Qué curioso, Jess no me los había mencionado. ¿Hace cuánto que se conocen?</p>
                
                <p>Dos horas antes de venir a mi cumpleaños, Jess me había llamado por teléfono preguntándome si no tenía inconveniente en que ella trajera invitados. Yo le dije que no había problema, pensé que sería algún familiar suyo.</p>
                <p>—Hace tres días —respondió la señora—. Nos conocimos esta semana.</p>
                
                <p>Yo solo abrí los ojos de par en par, sin dar crédito al poco criterio de mi amiga para relacionarse con desconocidos y traerlos a una fiesta íntima. Una risa nerviosa salió de mi boca.</p>
                <p>—Hay que cosas, pues qué bien, ¿no?</p>
                <p>—Así es… es que yo recientemente me acabo de divorciar y su esposa murió hace unos días. Nos hacía bien una salidita. Feliz cumpleaños, por cierto —me contestaron ellos.</p>
                
                <p>Con los ojos abiertos de par en par, respondí solo con un descolocado "gracias".</p>
                
                <p>No sé si sería por el alcohol, pero nunca me había percatado de que Jess siempre se relacionaba con personas densas. Ese tipo de personas tóxicas que siempre se están quejando de lo mal que les va en la vida, pero que en el fondo son ellos mismos los responsables de sus malas decisiones. En fin, o tal vez sí lo había notado, pero nunca me había tocado convivir con sus amigos.</p>
                
                <p>De vez en cuando volteaba a verla; seguía sin despegársele a mi primo. Él es muy guapo, la verdad, pero se supone que ella estaba aquí por mi cumpleaños, y se pasó toda la noche resbalándosele. Repito, no sé si era la botella y media de alcohol que para ese entonces ya me había bebido, pero nunca había notado esa personalidad en Jessica. A ella la conocí en la escuela de música y ella, al revés de mí, había hecho solo el propedéutico y luego desertó. Alguna vez me confesó que había entrado a la licenciatura porque le gustaban los rockeros, pero que la música no tanto. Aún no me explico cómo pasó los exámenes de admisión, que sí son muy difíciles. Supongo que ritmo sí tiene; eso lo comprobé después de verla bailar reguetón con mi primo.</p>
                
                <p>Mientras bailaba retorciéndosele a mi familiar, recordé mis aventuras con ella y me sorprendí de cómo había seguido la amistad, pese a haber dejado la carrera.</p>
                
                <p>De repente, en el móvil recibí un mensaje del número de Sofía, mi amiga de la licenciatura de administración: <em>"Lo siento, no podré ir, el bebé tiene reflujo y estoy muerta de cansancio. Espero me disculpes"</em>.</p>
                
                <p>—Macandy, ¿quieres que ya sirva la comida o esperamos a que lleguen los demás? —se acercó mi madre.</p>
                <p>—Sí, está bien —respondí.</p>
                <p>—Pero Sofía aún no llega, ¿no esperarás a Sofi?</p>
                <p>—Ella no vendrá.</p>
                <p>—¡Oh! —respondió mi mamá. Creo que notó mi cara de desconcierto, porque no dijo nada más y se fue.</p>
                
                <p>Mientras estudiaba la licenciatura en administración, la escuela había organizado un viaje cultural universitario al famoso Festival Cervantino. Éramos: Sofía, José Luis (su novio), mi novio de ese entonces (que la verdad no importa el nombre) y yo. Teníamos poco de haber ingresado a la carrera y todos nos caímos muy bien. Al final del día, todos estábamos eufóricos, ebrios y afónicos, ya que pasamos la mayor parte del viaje gritando y bebiendo. Ambos chicos se alejaron un momento porque mi novio ya no podía más y se puso a vomitar. Como las calles de esa ciudad son muy estrechas, nos sentamos en la fuente de una acera a esperarlos.</p>
                
                <p>La noche se puso sola y silenciosa. Entonces Sofía, tal vez por el alcohol, empezó a platicarme sobre su relación. Me contaba que su novio era muy duro con ella, que la maltrataba psicológicamente, pero que yo la hacía sentir como debía ser una mujer: segura de sí misma. Me decía que en el fondo quería ser como yo, que me admiraba. Yo no entendía por qué. En fin, se quebró, empezó a llorar y yo traté de consolarla. Ya más calmada, me dijo que no sabía por qué todos los hombres eran unos idiotas que no sabían escucharnos, etcétera. De repente, se quedó en silencio mirando mis ojos profundamente, bajó su mirada a mis labios y su cara se acercó a mi rostro... y me besó.</p>
                
                <p>En ese instante yo no supe qué hacer. Solo recuerdo que entrecerré mis ojos y me preguntaba: <em>¿Soy lesbiana? ¿Qué estaba pasando?</em>, me cuestioné. Un montón de cosas pasaron en mi cabeza en los segundos que duró ese beso. Se alejó de mí... y solo sonrió. Yo con cara de <em>¿WHAT?</em>. De la nada apareció José Luis.</p>
                <p>—Vámonos ya, Sofía —dijo él.</p>
                
                <p>Yo no lo había sentido llegar. ¿Nos vio? Me pregunté. Nunca lo supe, pero todo el viaje de regreso José Luis estuvo muy frío conmigo, apenas si me dirigió la palabra y evitaba el contacto visual.</p>
                
                <p>La comida no me supo. Jess no paraba de querer ser el centro de atención y hacía bromas para que todos la escucháramos. Yo, por mi parte, aun recordando aquel viaje al Cervantino después de haber recibido el mensaje de Sofía, pensaba en lo curioso que era mi amistad con ella y de cómo esta se había mantenido intacta a pesar de aquel incidente. Con los meses, luego de ese viaje, me cambié de carrera. Ella terminó la licenciatura en administración, se casó con José Luis, tuvieron un hijo y habíamos mantenido el contacto todo este tiempo regularmente. Pero ya teníamos más de un año de no vernos porque me había volcado en mis estudios finales. Tenía muchas ganas de verla. Sin embargo, no llegó. Siempre supuse que su esposo se sentía incómodo con nuestra amistad, bueno, después de ese beso, si es que nos vio, porque antes nos llevamos muy bien. Pero siempre supe que eso no significó nada para ella; en realidad, tampoco para mí. Las mujeres podemos manejar ese tipo de situaciones muy bien. No tanto así los hombres.</p>
                
                <p>Mi mejor amigo gay, que en estos momentos come junto a mí como si no hubiera mañana, vivió algo así con su mejor amigo. Literalmente vivió la historia de la película <em>Y tu mamá también</em>, se los juro. Es más, Alfonso Cuarón se inspiró en su historia para rodar esa película, con todo y el baile con la canción de Los Bukis. Lo juro por Christian Dior. Bueno, esa es la broma que siempre cuento enfrente de él cuando la situación viene al caso. Lo que supe después de ese día es que yo era bisexual, y que podía estar con otras chicas sin ningún problema. Eso sumó puntos en mis relaciones posteriores, ya que a ninguno de mis novios le parecía mal. Bueno, debo aclarar que todos fueron músicos. En fin, músicos, ¿qué les puedo decir?</p>
                
