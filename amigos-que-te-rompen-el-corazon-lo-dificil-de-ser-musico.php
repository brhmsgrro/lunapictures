                <blockquote>
                    "Como en toda relación, cuando no le importas al otro, sea tu jefe, tu amigo, tu compañero, siempre hay algo que no sabes qué es y que te molesta, pero que no puedes reclamar, porque solo se le reclama a la gente con la que tienes algo íntimo, como una pareja."
                </blockquote>
                
                <p>Y cuando alguien te hace daño, se lo dices. Pero con los amigos se suele tener más paciencia y solo dices: "No hay problema, no pasa nada, somos amigos". Eso hacen los amigos: se perdonan y lo dejas pasar, y simplemente no dices nada. Entonces no sabes qué es lo que ha cambiado en la relación y empiezas a distanciarte.</p>
                
                <p>Y como en todas las relaciones interpersonales, algunas personas se irán de tu vida, así como otras entrarán, y está bien. Eso es parte de crecer. Sería imposible tener los mismos amigos desde la infancia; a eso se le llama madurar. Pero si tienes los mismos amigos, ¿quiere decir que algo has hecho mal? No lo sé.</p>
                
