					<p class="text-justify">En ese entonces rondaba yo los 17 - 18 años; más o menos, a esa edad uno “cree que sabe”, pero realmente uno “no sabe nada”. Supongo que todos en esa etapa solemos ser relativamente ingenuos, trincados y en ocasiones crédulos, pero sobre todo si naces con un espíritu inquieto; con muchas ganas de aprender. En tu cabeza está el ser alguien en la vida (aunque el profesor de filosofía siempre te increpaba que ya eras alguien en la vida).</p> 

          <p class="text-justify">En fin, en ese entonces harto de mis padres quería la emancipación; y buscando trabajo fue como di con ese anuncio espectacular:<i> “se solicita auxiliar de oficina, solo 4 horas diarias, contestando teléfonos, $1500 a la semana, a partir de 16, no se necesita experiencia” </i> …uno joven y sin saber de qué va la vida realmente, termina respondiendo a este tipo de anuncios, preso de la curiosidad.</p>
          <p class="text-justify">Para ahorrar un poco el rodeo, llegué a las oficinas, me entrevistaron y dijeron: “empiezas el lunes” yo dije: “ok” ...me habían avisado que habría dos semanas, (o una no recuerdo, pero me pareció una eternidad en ese entonces) de capacitación previa, pero que esta estaba pagada, así que ¡todo perfecto! Pensé.
Me presento a las 9:00 am, me pasan a un salón donde aproximadamente había unas 70-80 gentes. A mí me parecían muchas, me sentaron en una de las últimas filas, (había gente de todas las edades, hasta de unos 60 años, más o menos. y creo que era de los más jóvenes, si no es que el más joven, no recuerdo haber hecho amistad con nadie de mí misma edad, además, la capacitación terminaba a las 1 o 2pm… el primer día recuerdo que me dolían las sentaderas de haber permanecido sentado tantas horas. 
La capacitación, parecía más el público de un show de televisión, con toques de evento de superación personal, aderezado con un retiro espiritual, (sí también alguna vez fui a ese tipo de cosas) y comenzó el lavado de cerebro.</p>
<p class="text-justify">Nos explicaron la diferencia entre ricos y pobres, que nuestra familia no nos deja avanzar, que los amigos, que somos especiales y que todos teníamos un gran potencial en nuestra vida, pero por x o y razón no alcanzábamos nuestro desarrollo pleno. Pero ¡oh, sorpresa! ellos estaban ahí para ayudar, nos dirían como, nos Darian una formula infalible para dejar la mediocridad y ser personas plenas y exitosas.</p>
<p class="text-justify">Cantábamos, gritábamos, nos enajenábamos, mientras nos convencíamos cada vez más que haríamos todo para dejar de ser mediocres y ser exitosos, sin embargo, la formula nunca llegaba, no la decían, cómo es que trabajaríamos, qué es lo que haríamos, nada.
Para esto previamente nos habían dicho que, por haber participado en esa capacitación, como regalo, a parte de nuestro sueldo, nos Darían una canasta con productos de belleza (cremas, aceites, lociones, etc) que eran precisamente lo que ellos vendían. De hecho, se hacían llamar una “comercializadora”, pues genial, que venga la canasta. </p>
<p class="text-justify">Cabe mencionar que, desde el primer día hasta el último, 
conforme se desarrollaba la capacitación el numero de personas fue bajando considerablemente, de ser 80 – 90 personas, al final quedamos 5.
Se nos dijo también en su momento que teníamos que firmar un contrato, el cual solo podría ser firmado después de hacer una inversión de $2500.  Que era un requisito para formar parte de su negocio, y que era una cuota que se debía pagar, y aquí viene lo que toda persona con sensatez podría pensar “estoy buscando trabajo, porque no tengo dinero… ¿por qué tengo que poner dinero para ganar dinero?” Pero bueno cuando uno monta un negocio sabe que se tiene que invertir, pones dinero de tu bolsa para generar más dinero, a la edad de 17 uno piensa; “pues bueno”.</p>
<p class="text-justify">Conforme se acercaba el ultimo día de capacitación, la verdad se iba revelando, la famosa canasta “de regalo” tenía una función curiosa. Una de las ponentes, lanzo esta idea al aire: “yo les voy a decir como multiplicar su dinero: ésta canasta es de regalo, pero mejor ¿por qué no la venden? y así obtienen un dinero por la canasta, en lugar de usarla… o mejor aún, rífenla, de tantos boletos, sale tanto, si aquí hay $2,500 en valor de producto (recordemos que ese era el mismo número que pedían en dinero para entrar al negocio) ustedes pueden duplicar o hasta triplicar el monto, depende del número de boletos vendidos… " buena idea pensé yo, pero no me gusta hacer ese tipo de cosas, yo era muy tímido,  una vez dentro de la empresa regalaría la canasta a mi familia, en fin. 
Hasta aquí todo bien, solo que había un pequeño problema, de donde sacaría un chaval de 17 la cantidad de $2,500 si precisamente no tenía empleo ¿???? Pues bueno, todo ese tiempo de la dichosa capacitación se nos instruyo en la forma de conseguirlo, que realmente eran técnicas para pedir prestado; a tus amigos, conocidos, etc. no había pierde, duplicarías ese dinero: los $1500 a la semana (solo 4hrs diarias), mas lo de la canasta... a esa edad  uno se quiere comer el mundo (yo lo hice), ahora que veo hacia atrás no sé cómo, en ese entonces me parecía mucho dinero, pero lo logre 
Llegó el día del cierre y entregué el dinero. Se había dicho que habría un evento en el que podrías invitar a tu familia sería un convivio pagado por la empresa, deberías entregar el dinero primero… Pero ese día no hubo nada, de todos los días anteriores de alegría euforia y adrenalina, ese día todo el ánimo se encontraba por los suelos y la verdad salió a la luz. </p>

<p class="text-justify">La idea desde el principio había sido que compráramos las canastas, así de sencillo. Después de hacer eso, sí obtendríamos un trabajo, pero reclutando a más crédulos. Nosotros pondríamos anuncios en el periódico (de nuestro dinero) y contestaríamos los mentados teléfonos, eso durante 4hrs diarias, y por cada incauto que consiguiéramos se nos daría una comisión, actualmente tengo 32 y no me parece una idea tan mala, pero entonces ¿porque me sigue sonando a una estafa? 
Estaba en shock, todo eso lo entendí en el último momento, cuando tenía el contrato frente a mí, en mis manos, no sabia que hacer, en el grupo de 5 gentes había una señora de 30, otro de 50, y los otros rondando los 20´s…  y yo… recuerdo le dije a la señora, “¿esto es lo que nos prometieron o entendí mal?” la señora me dijo: “no, efectivamente nos mintieron” se armó un zafarrancho, pedí hablar con los encargados, yo tenía mucho miedo de perder mi dinero, entre en estado de pánico, cómo regresaría con mi canasta, (y con un talonario, porque curiosamente ya los tenían impresos, para quien lo quisiera) cómo les pagaría a mis amigos, la cabeza me daba vueltas y me sentí mareado…  Al ser un grupo de gente molesta no tuvieron mas remedio que regresarnos el dinero. y recuerdo también que solo el hombre de 50 años, firmo el contrato, se lo llevaron a otro salón para que no estuviera con nosotros.</p>
<p class="text-justify">Regrese como perro con la cola entre las patas; porque lo que no les Conte fue que, durante este proceso, discutí con mis padres, mi papá me advirtió del fraude y mi mamá me dijo que me apoyaría, pero no me prestaría el dinero para entrar a esa empresa, que era ilógico que pagara para poder trabajar. Realmente había hecho efecto el “coco wash”, porque lograron que hiciera lo que ellos querían, conseguirles el dinero pese a lo que fuera. Finalmente paso el tiempo pague a mis acreedores, y así termino la historia. </p>
<p class="text-justify">Les había mencionado que esa experiencia fue sumamente dolorosa, definitivamente algo se quebró dentro de mí, la ingenuidad supongo, pero también la fé dejé de creer en las personas y durante muchos años no pude leer un libro de autoayuda: “malditos, te hacen creer que quieren ayudarte, pero solo quieren tu dinero” … pensé. 
Años después alguien me recomendaba insistentemente leyera el libro “padre rico padre pobre” de Robert kiyosaki y me resistí a leerlo durante un buen tiempo, todo lo que sonara a que "puedes ser rico y feliz" sonaba a multinivel para mi… 
Finalmente leí ese libro, fue el primero que leí sobre finanzas personales, y si bien es un libro que entra dentro del rubro de superación personal, auto desarrollo, motivación… etc.. etc, es un libro que todo emprendedor debe leer, ese libro también me regreso la confianza en emprender y volví al ruedo... pero eso da para otras historias. 
Y bueno ya está, supongo que no seria quien soy de no haber vivido esa experiencia, supongo que todo lo que te hace crecer causa dolor, ¿no lo crees?</p>
