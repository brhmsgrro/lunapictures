            <article class="editorial-body">
                <p class="drop-cap">En ese entonces rondaba yo los 17 o 18 años. Más o menos, a esa edad uno "cree que sabe", pero realmente uno "no sabe nada". Supongo que todos en esa etapa solemos ser relativamente ingenuos, trincados y en ocasiones crédulos, pero sobre todo si naces con un espíritu inquieto; con muchas ganas de aprender. En tu cabeza está el ser alguien en la vida, aunque el profesor de filosofía siempre te increpaba que ya eras alguien en la vida.</p> 

                <p>En fin, harto de mis padres, quería la emancipación. Buscando trabajo di con ese anuncio espectacular: <em>"se solicita auxiliar de oficina, solo 4 horas diarias, contestando teléfonos, $1500 a la semana, a partir de 16, no se necesita experiencia"</em>. Uno, joven y sin saber de qué va la vida realmente, termina respondiendo a este tipo de anuncios, preso de la curiosidad.</p>
                
                <p>Para ahorrar el rodeo: llegué a las oficinas, me entrevistaron y dijeron: "empiezas el lunes". Me habían avisado que habría dos semanas de capacitación previa, pagada. Todo perfecto, pensé. Me presento a las 9:00 am a un salón con aproximadamente 70 u 80 personas. Me sentaron en las últimas filas. El primer día recuerdo que me dolía el cuerpo de haber permanecido sentado tantas horas.</p>
                
                <p>La capacitación parecía más el público de un show de televisión, con toques de evento de superación personal aderezado con un retiro espiritual, y así comenzó el lavado de cerebro. Nos explicaron la diferencia entre ricos y pobres, que nuestra familia no nos deja avanzar, que somos especiales y que todos teníamos un gran potencial. Pero ¡oh, sorpresa! ellos estaban ahí para ayudar, nos darían una fórmula infalible para dejar la mediocridad.</p>
                
                <p>Cantábamos, gritábamos, nos enajenábamos, convenciéndonos de que haríamos todo para ser exitosos. Sin embargo, la fórmula nunca llegaba. Previamente nos habían dicho que, por haber participado, nos darían una canasta con productos de belleza como regalo.</p>
                
                <p>Conforme avanzaban los días, el número de personas bajó considerablemente; de 80 a solo 5. Se nos dijo que teníamos que firmar un contrato, pero solo después de hacer una inversión de $2,500. Aquí viene lo que toda persona con sensatez podría pensar: <mark>"estoy buscando trabajo porque no tengo dinero… ¿por qué tengo que poner dinero para ganar dinero?"</mark></p>
                
                <blockquote>
                    "La idea desde el principio había sido que compráramos las canastas. Después de hacer eso, obtendríamos un trabajo reclutando a más crédulos."
                </blockquote>
                
                <p>Conforme se acercaba el último día, la verdad se reveló. La famosa canasta "de regalo" tenía una función curiosa. Una ponente lanzó la idea: "mejor véndanla o rífenla". El problema era: ¿de dónde sacaría un chaval de 17 años $2,500 si precisamente no tenía empleo? Se nos instruyó en técnicas para pedir prestado a amigos y conocidos. Lo logré.</p>

                <p>Llegó el día del cierre y entregué el dinero. Pero ese día no hubo convivio. De toda la alegría y euforia anteriores, el ánimo se desplomó y la verdad salió a la luz. Nosotros pondríamos anuncios en el periódico con nuestro propio dinero y, por cada incauto que consiguiéramos, se nos daría una comisión.</p>
                
                <p>Estaba en shock. En el grupo de 5 personas, le pregunté a una señora: "¿esto es lo que nos prometieron o entendí mal?". Ella respondió: "no, efectivamente nos mintieron". Se armó un zafarrancho. Tenía mucho miedo de perder mi dinero, entré en pánico, ¿cómo les pagaría a mis amigos? Al ser un grupo de gente molesta, no tuvieron más remedio que regresarnos el dinero.</p>
                
                <p>Regresé como perro con la cola entre las patas. Mi papá me había advertido del fraude y mi mamá me dijo que era ilógico pagar para poder trabajar. El "brainwashing" había hecho efecto, logrando que consiguiera el dinero pese a todo. Finalmente pagué a mis acreedores, y así terminó la historia.</p>
                
                <p>Esa experiencia fue sumamente dolorosa. Algo se quebró dentro de mí: la ingenuidad, pero también la fe. Dejé de creer en las personas y durante muchos años no pude leer un libro de autoayuda. Pensaba: "malditos, te hacen creer que quieren ayudarte, pero solo quieren tu dinero".</p>
                
                <p>Años después, alguien me recomendó insistentemente leer <em>"Padre Rico, Padre Pobre"</em> de Robert Kiyosaki. Me resistí; todo lo que sonara a "puedes ser rico y feliz" me sonaba a multinivel. Finalmente lo leí. Fue el primero que leí sobre finanzas personales y, si bien entra en el rubro de superación personal, es un libro que todo emprendedor debe leer. Ese libro me regresó la confianza en emprender y volví al ruedo.</p>
                
                <p style="font-size: 1.25rem; font-weight: 600; color: #121212; margin-top: 3rem; border-top: 1px solid #e2e2e2; padding-top: 2rem;">
                    Supongo que no sería quien soy de no haber vivido esa experiencia. Todo lo que te hace crecer, causa dolor. ¿No lo crees?
                </p>
            </article>

