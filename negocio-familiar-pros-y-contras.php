            <article class="editorial-body">
                <p class="drop-cap">La fila para pagar en la tienda de cárnicos de mi ciudad estaba bastante lenta. No era un día especial, pero el proceso, generalmente simple, estaba tomando más de lo normal. ¿"Qué pasa?", me pregunté. Resulta que la cajera estaba teniendo un lío para cobrar porque un cliente la había "mareado": preguntando por esto y aquello, haciendo un pedido, pagándolo, cancelándolo, pidiendo su dinero de vuelta y pagando solo una parte. Un "mareador". En América Latina podría tener muchos nombres, pero no es más que una persona que te confunde y que al final te perjudica económicamente.</p> 

                <p>Yo entendía que la chica acababa de ser víctima de una estafa. En su mente intentaba descifrar qué había pasado, sin dejar de cobrar, pero estaba descolocada emocionalmente y no podía concentrarse. La lista de pedidos crecía. Al final tuvo que intervenir otra chica con más experiencia y la fila comenzó a avanzar. Me di cuenta de que la joven estafada era en realidad una de las hijas de los dueños; una chica que al parecer no suele trabajar en el negocio familiar y se notaba su falta de experiencia en la vida. Total, se acercó su madre y la chica empezó a explicar lo sucedido, muy preocupada.</p>
                
                <p>Me di cuenta de lo afortunado que había sido (y no) ya que mis padres todo el tiempo hicieron que ayudase con el negocio familiar. No había fines de semana ni días festivos. Así crecí, y actualmente me da mucho trabajo saber qué día es festivo, ya que mi calendario laboral no depende de eso. A diferencia de los oficinistas, cuyas semanas giran en torno a las efemérides del mes, yo vivo con un ritmo distinto.</p>
                
                <p>El punto es: ¿por qué muchos padres no involucran a sus hijos en los negocios familiares? Finalmente, deberíamos prepararnos para el retiro y pasar la estafeta en algún momento dado, ¿no?</p>
                
                <p>Me imagino que es el temor a que los hijos terminen haciendo "algo que no nos gusta". Siempre está el deseo de algunos progenitores de ver a los hijos convertidos en ejecutivos exitosos de traje y con carro del año, viviendo en uno de los suburbios más lujosos, porque nos han vendido que así luce el éxito. Creen que la única forma de lograrlo es que los hijos se dediquen solamente a los estudios universitarios, mientras el padre trabaja solo para que el hijo pueda concentrarse en sus deberes escolares. Solo para descubrir después que la vida de un profesionista puede ser bastante frustrante y limitada, y que los oficios tienen bastantes más ventajas de las que pensaban en un principio.</p>
                
                <blockquote>
                    "Muchas de las veces, cualquier oficio es tan o hasta más rentable que una profesión. Y sobre todo, en el mercado laboral parece que se paga mejor lo que nadie quiere hacer."
                </blockquote>
                
                <p>Regresemos a los oficios que giran en torno a un negocio familiar. Tal vez a un mecánico no le gustaría que su hijo termine siendo mecánico, porque solemos proyectar nuestras frustraciones y anhelos a través de nuestros vástagos. Pero, ¿le hará daño al chico saber un poco de qué va el oficio? No creo que a ningún chaval le resulte "de más" saber cómo está compuesto un motor.</p>
                
                <p>Ese chico puede perfectamente alternar sus deberes estudiantiles con un trabajo de medio tiempo en el negocio familiar. Cuando llegue a la universidad, podrá hacerse cargo del negocio con una preparación profesional. Y como recordó cómo se desarma un automóvil, sabe de qué va el negocio. En el mejor de los escenarios, tendríamos un buen administrador que puede seguir con la tradición familiar, o a un profesionista exitoso que también sabe cómo cambiar las bujías de su auto.</p>

                <h3>Hacerse su propio camino</h3>
                
                <p>Creo que el sueño de todo padre es que los hijos se puedan valer por sí mismos. En ocasiones, darles todas las comodidades que uno no tuvo, la mayoría de las veces vuelve a los hijos en unos completos "catetos" que ni estudiaron ni saben del negocio familiar.</p>
                
                <p>Por otro lado, están los hijos que sueñan con tener su propia vida y no vivir a la sombra de los padres. Muchas de las veces sus intereses distan completamente de la profesión paternal. Pero insisto: cuando llegue la gran oportunidad para los hijos, ¿estaría de más que supieran cómo es el negocio de la familia? Yo creo que no. Todo se puede hacer.</p>
                
                <p>Recuerdo que en una ocasión mi madre me decía que trabajar para otras personas sería completamente diferente y no sería tan bueno como imaginaba. Afortunadamente, tuve la oportunidad de trabajar en algunas empresas (incluso de limpieza) y efectivamente el trato fue completamente distinto. No estaban las consideraciones por ser el hijo del dueño: la paga era mala y los regaños eran diferentes. Incluso recuerdo que después de unos meses me di cuenta de la mentalidad que tiene la gente que trabaja para otros. Es una estructura mental que no compartía con ellos, por estar educado de otra forma. Pero, en fin, incluso de ese trabajo aprendí un montón de cosas que, cuando regresé a trabajar con mis padres, les dije que podríamos aplicar. Y así lo hicimos.</p>

                <h3>El hijo se hace adulto</h3>
                
                <p>Mucho tiempo después, ya convertido en padre de dos muchachos, escuché al menor de ellos (ambos trabajaban en el restaurante de su abuela) referirse a sí mismo en un tono superior ante otros empleados como "el hijo del dueño". Comentario que me pareció inapropiado y lleno de soberbia, así que lo reprendí.</p>
                
                <p>Cuando llegó el divorcio de mi esposa, los chicos se fueron a vivir con su madre y ambos tuvieron que trabajar en distintos oficios. Debo reconocer que el mayor era ya bastante engreído, porque prácticamente se veía como el gerente del restaurante. Finalmente, se le bajaron los humos cuando tuvo que trabajar con su ahora padrastro en la industria de la construcción, con un montón de obreros más, donde ya no tenía ni la titularidad ni su padrastro era gerente de nada. El menor empezó a trabajar en un puesto de botanas callejeras (se volvió más suelto con la lengua, eso sí), pero adquirió un tono más empático con las personas que antes no tenía.</p>
                
                <p>Un año después de mi fracaso matrimonial pude asentarme financieramente de nuevo y volví a emprender con un "Food truck" de comida rápida. Los chicos trabajan conmigo y los veo más atentos, más comprometidos y más humildes. El mayor está por entrar a la universidad; no sé qué estudiará. El menor fue un caso aparte; luego del colegio secundario ya no quiso seguir estudiando. Supongo que la separación le sentó mal, por estar en plena adolescencia.</p>
                
                <p>En fin, sea lo que sea que hagan, creo que el tiempo que compartimos trabajando en la misma empresa les servirá. Ya sea para darle continuidad al negocio familiar o para que ellos monten sus propios emprendimientos, lo más importante es que crezcan con mentalidad emprendedora. Se puede trabajar con tu familia e ir por "el sueño de actor de cine" al mismo tiempo. Si funciona, ¡qué genial!, sabes más cosas. Y si no resulta, puedes seguir intentándolo mientras ayudas a que el negocio de la familia vaya "pa'lante".</p>
                
                <p style="font-size: 1.25rem; font-weight: 600; color: #121212; margin-top: 3rem; border-top: 1px solid #e2e2e2; padding-top: 2rem;">
                    Algo que he aprendido a mis cuarenta y cinco es que, finalmente, la manzana no cae muy lejos del árbol. Somos, como alguien dijo alguna vez, la versión mejorada de nuestros padres. Y para mí, eso se ha vuelto una verdad absoluta.
                </p>
