          <p class="text-justify">La fila para pagar en la tienda de cárnicos de mi ciudad, estaba bastante lenta, no era un día especial o diferente a los demás, pero la fila simplemente no avanzaba y lo que generalmente es un proceso bastante simple estaba tomando más de lo normal, ¿”Qué pasa?” me pregunte; generalmente no suelo ser una persona desesperada y mucho menos “más curiosa” de lo que se debería, prácticamente vivo en mi mundo salvo que algo perturbe la monotonía de mi día; solo entonces pongo atención en los chismes: resulta que la cajera estaba teniendo un lio para cobrar porque un cliente la había “mareado”, preguntando por esto y por aquello, haciendo un pedido pagándolo y luego cancelando, pidiendo de vuelta su dinero, pagando solo una parte, pero dejando esto, etc., etc.… un “mareador”, (eso lo había visto pero no lo había entendido) en América latina podría tener muchos nombres pero vamos no es más una persona que te confunde y que al final te perjudica económicamente (casi siempre te ganan la mercancía, el dinero, y hasta el cambio) … yo entendía que la chica acababa de ser victima de una estafa, y en su mente intentaba saber que había pasado, no dejando obviamente de cobrar, total, la chica estaba descolocada emocionalmente, y no podía concentrarse en seguir con su trabajo; y la lista de pedidos de salida crecía, varias bolsas de carne, esperaban en el mostrador para que sus dueños pagasen y los recogiesen. Yo era el cliente numero 10 aproximadamente y ya no era una fila, era una veintena de personas todos queriendo pagar al mismo tiempo. Al final tuvo que intervenir otra chica que tenia mas experiencia en la caja y vamos la fila comenzó a avanzar el lio comenzó a irse, me di cuenta que esta chica (la que fue estafada), era en realidad una de las hijas de los dueños; ya saben una chica muy pija, piel blanca de cabello castaño, que al parecer no suele trabajar en el negocio familiar y pues se notaba su falta de experiencia en la vida… Total se acercó su madre y otras mujeres trabajadoras de la tienda y la chica empezó a explicar lo sucedido muy preocupada.</p>

<p class="text-justify">Me di cuenta o afortunado que había sido (y no) ya que mis padres todo el tiempo hicieron que ayudase con el negocio familiar, no había fines de semana ni días festivos, así crecí y actualmente me da mucho trabajo saber qué día es festivo, ya que mi calendario laboral no depende de eso - ¿No un día, iba yo muy fresco al banco y resultó que estaba cerrado por ser el día de la Nación?… ¡que putada… pensé! -   digo a diferencia de los oficinistas y cualquier obrero que sus semanas giran entorno a las efemérides del mes, que saben que días son de asueto y se previenen con anticipación. Pero bueno ese no es el punto, el punto es ¿Por qué muchos padres no involucran a sus hijos en los negocios familiares? Digo finalmente deberíamos prepararnos para el retiro y pasar la estafeta en algún momento dado ¿No? …</p>

 <p class="text-justify">Me imagino que es el temor a que los hijos terminen como uno haciendo “algo que no nos gusta”, no lo sé, o pensamientos de ese tipo, por otro lado siempre esta el deseo de algunos progenitores de ver a los hijos convertidos en ejecutivos exitosos de traje y con carro del año, viviendo en uno de los suburbios más lujosos de la ciudad, porque nos han vendido que así luce el éxito;  y saben que la única forma de que lo consigan es que los hijos se dediquen solamente a los estudios universitarios y el tendero que vende jamón, o el panadero esta dispuesto a trabajar solo (bueno y con otros trabajadores) para que su hijo pueda concentrarse en lo deberes escolares. Ya luego para descubrir que la vida de un profesionista puede ser bastante frustrante y limitada… y que sus oficios tienen bastantes más ventajas de las que pensaban en un principio, que carajos.</p></br>

<p class="text-justify">Todo eso esta genial, pero creo que los a hijos siempre les vendrá muy bien empaparse de lo que hacen sus progenitores, no solo para terminar haciendo lo mismo que ellos, pero además ¿qué de malo tiene, seguir los pasos de alguno de los padres?… Muchas de las veces cualquier oficio es tan o hasta mas rentable que una profesión. Y sobre todo en el mercado laboral parece que se paga mejor lo que nadie quiere hacer, un obrero de la construcción principiante puede llegar a ganar mucho más que el chico que trabaja en el mostrador de una tienda de conveniencia cualquiera, dicho sea de paso, que para tener ese puesto, éste, tuvo que haber hecho mínimo el bachiller…</p>
Pero bueno regresemos a los oficios que giran en torno a un negocio familiar, tal vez a un mecánico no le gustaría que su hijo termine siendo mecánico igual que él, porque solemos proyectar nuestra frustraciones y anhelos a través de nuestros vástagos y talvez no quieren influir al hijo para que se dedique a lo mismo que él - luego cuando los hijos demuestran animadversión al trabajo del padre ese es otro problema- Pero ¿Le hará daño al chico saber un poco de que va el oficio de mecánico? … no creo que a ningún chaval le resulte “de más” saber cómo está compuesto un motor, y que es lo que hace andar al vehículo. No la verdad es que no esta demás, ese chico puede perfectamente alternar sus deberes estudiantiles con un trabajo de medio tiempo en el negocio familiar y que cuando llegue a la universidad el chico pueda hacerse cargo del negocio, pero con una preparación profesional y si recordamos que este chico paso horas armando y desarmando un automóvil  sabe de qué va el negocio y por ende en el mejor de los escenarios tendríamos un buen administrador que puede seguir con la tradición familiar; O a un profesionista exitoso que también sabe cómo cambiar las bujías de su auto. </p>
</br>

<h3>Hacerse su propio camino</h3></p>

<p class="text-justify">Creo que el sueño de todo padre es que los hijos se puedan valer por si mismos y en ocasiones darles todas las comodidades que uno no tuvo la mayoría de las veces vuelve a los hijos en unos completos “catetos” … que a veces ni estudiaron y ni saben del negocio familiar. 
Por otro lado, están los hijos que sueñan con tener su propia vida y no vivir a la sombra de los padres, y muchas de las veces sus intereses distan completamente de la profesión paternal, pero insisto en lo que llega la gran oportunidad para los hijos, estaría de mas supieran como es el negocio de la familia, yo creo que no, yo creo que todo se puede hacer.</p>

<p class="text-justify">Recuerdo que en una ocasión mi madre me decía que el trabajar para otras personas seria completamente diferente y no seria tan bueno como imaginaba etc. etc.… afortunadamente tuve la oportunidad de trabajar en algunas empresas (incluso de limpieza) y efectivamente  el trato fue completamente distinto principalmente porque no estaban las consideraciones por ser el hijo del dueño, la paga era mala, los regaños eran diferentes aunque no eran buenos se sufrían de forma distante… no como cuando te regañaba papá por haber estropeado una pieza del torno.  Incluso recuerdo que después de unos meses me di cuenta la mentalidad que tiene la gente que trabaja para otros… es rara digamos que muchas de las veces son personas que no tienen espíritu de aventura (que es lo que muchas de las veces caracteriza a los emprendedores) es una sencilla estructura mental que me di cuenta no compartía con ellos, por estar educado de otra forma digo, pero en fin incluso de ese trabajo aprendí un montón de cosas que cuando regrese a trabajar con mis padres les dije que podríamos aplicar cosas como las que vi en esa empresa, y así lo hicimos. </p></br>


<h3>El hijo se hace adulto</h3></p>

<p class="text-justify">Mucho tiempo después ya convertido en padre de dos muchachos escuché al menor de ellos, (ambos trabajaban en el restaurante de su abuela), referirse a sí mismo en un tono superior ante otros empleados como el hijo del dueño, comentario que me pareció inapropiado y lleno de soberbia, le reprendí por eso. Cuando llego el divorcio de mi esposa los chicos se fueron a vivir con su madre y ambos tuvieron que trabajar en distintos oficios, debo reconocer que el mayor era ya bástate engreído porque prácticamente se veía como el gerente del restaurante de la abuela, finalmente se le bajaron los humos cuando tuvo que trabajar con su ahora padrastro en la industria de la construcción con un montón de obreros más y donde ya no tenía ni la titularidad ni su padrastro era gerente de nada, el menor empezó a trabajar en un puesto de botanas callejeras  (se volvió mas suelto con la lengua eso sí) pero adquirido un tono más empático con las personas que antes no tenía. 
</p></br>

<p class="text-justify">Un año después de mi fracaso matrimonial pude asentarme financieramente de nuevo (esos divorcios siempre te dejan en la calle) y volví a emprender con un “Food truck” de comida rápida… los chicos trabajan con migo y los veo mas atentos, mas comprometidos mas humildes, el mayor esta por entrar a la universidad, no se que estudiara, el menor si fue un caso aparte, luego del colegio secundario ya no quiso seguir estudiando, supongo que la separación le sentó mal, por estar en plena adolescencia, en fin, sea lo que sea que hagan creo yo el tiempo que compartimos trabajando en la misma empresa les servirá, ya sea para darle continuidad al negocio familiar o para que ellos monten sus propios emprendimientos, pero lo mas importante es que crezcan con mentalidad emprendedora. Creo yo todo se puede hacer, trabajar con tu familia e ir por “el sueño de actor de cine” todo, si funciona pues que genial sabes más cosas y si no resulta, puedes seguir intentándolo mientras ayudas a que el negocio de la familia vaya “pa lante” y conseguir tus sueños… Pero bueno algo que aprendido a mis cuarenta y cinco: es que finalmente la manzana no cae muy lejos del árbol, somos como alguien dijo alguna vez, la versión mejorada de nuestros padres y para mí se ha vuelto una verdad. </p>
