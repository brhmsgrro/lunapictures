  1. Fui empresario hasta los 38 años. Enrique mi hermano y yo fundamos una empresa de alimentos cuando él tenía 24 y yo 20. Estudiaba Ciencias de la Comunicación y él era ingeniero analista de tiempos y movimientos en Banca Serfín. 
2. Un día se preguntó por qué no había miel de abeja en porción individual, así como la mermelada y la mantequilla. Nosotros teníamos abejas desde que éramos niños en Tequila. Así que diseñó unas máquinas. Fue con el tornero, el laminero y con su segundo sueldo compró un compresor.
3. Él mismo armó las máquinas y cuando creyó que estaban listas pidió un préstamo en su trabajo, 30 mil pesos (30 millones en aquel entonces) con intereses de empleado. Ya había planeado salirse de Serfín y negoció con su jefe que le sostuvieran esos intereses un año más.
4. Con ese capital comenzamos él y yo, luego contratamos a un empleada, Mónica Ramírez, que estaría con nosotros hasta el final, 18 años después. Las máquinas las instalamos en un cuarto de vecindad de 50 metros cuadrados en la Zona Roja de la ciudad. A la vuelta estaba el Guadalajara de Día.
5. Con esas máquinas manuales producíamos al día 6 cajas de 400 piezas de 30 gramos de miel. Yo era el único vendedor y en mis horas libres de la universidad, llenaba mi vocho 66 con cajas y vendía en cafeterías, clubes deportivos, hoteles, cafeterías de Guadalajara. 
6. Pero nadie me compraba nada. Llegamos a tener un inventario de 300 cajas en almacén. Conocí la importancia de un compresor. Las porciones individuales era imposible de abrirse. Ni con cuchillo. Pero teníamos que pagar la renta y la nómina de las 7 empleadas que ya teníamos. 
6. Las mujeres siempre fueron las mejores trabajadoras. Responsables, puntuales, comprometidas. Mi hermano rediseñó sus máquinas. Se pasaba horas armándolas y desarmándolas hasta que dio con la temperatura para el sellado. 
7. El negocio creció y nos mudamos a una bodega de 250 metros cuadrados en Zapopan. Ya teníamos 14 obreras, entre ellas Saile Fonck, pero los clientes no se multiplicaban con la misma velocidad. El mercado nos pedía mermelada de fresa y la incluimos. Todo lo comprábamos hecho, nosotros sólo envasábamos. 
8. En 1992 dimos el gran salto. Mi hermano consiguió otro préstamo con el banco y su aval fue el papá de un amigo que tenía una gran empresa de refrigeración, Reacsa. A don Ricardo Martínez le admiraba mucho el tesón de mi hermano. 
9. Serfín otra vez nos prestó, pero ahora fueron 350 mil dólares. Con esa línea de crédito compramos una máquina italiana. El Ferrari de las máquinas. Podía producir 1500 cajas de 240 piezas de 20 gramos en una hora. 
10. Nos mudamos a una bodega de mil metros cuadrados en la Zona Industria de Guadalajara, a la cual, como si fuera a pasar el Metrobús, tuvimos que cambiarle el piso a uno de concreto, para que aguantara el peso. Estábamos a pocas calles estaba Jabón Lirio y Salsa Valentina. Entonces sí nos sentimos empresarios. Ya teníamos 50 obreros.
11. Comenzamos a fabricar todo: comprábamos la fresa en Zamora (llegamos a comprar 600 toneladas a la semana), el azúcar, la pectina y hacíamos nuestra propia mermelada. Guadalajara nos quedó chiquita y el 27 de julio de 1992 me mudé a vivir a la Ciudad de México. Tenía que conseguir clientes que le dieran trabajo a esa máquina de 350 mil dólares. En ese entonces yo tenía 25 años.
12. Me aventé sin coche y sin conocer la ciudad. Me movía en metro y en pesero con mis cajas de miel y mermelada. Mis primeros dos años en la gran capital no vendí nada. Tenía 25 pero parecía de 20. Los compradores de Vips, Sanborns, Toks, Cocinas del Aire, eran 30 o 40 años mayores que yo.
13. Nada de Jóvenes Construyendo el Futuro. Yo lloraba. No vendía nada y tenía que sostener a la fábrica en Guadalajara. Caminaba la ciudad entera cargando mis cajas. Lloraba y me preguntaba qué hago aquí. 
14. De tanto tocar puertas yo me decía: alguna se tiene que abrir, con que entre con uno de los grandes ya la hice. Y entré. Juan Manuel Vazquez Arrieta de Wings fue el primero que me compró mis productos. Enseguida cayó Toks y Sanborns. Vips fue la joya de la corona. 
15. En sus mejores épocas, Vips me llegó a comprar un tráiler completo cada semana. 4 mil cajas de mermelada para sus bisquets. Directo de la fábrica a su comisariato en Rojo Gómez, sin pasar por mi almacén. 
16. 18 años después, Abal (así se llamaba la compañía) tenía una red de distribuidores en todo el país. Éramos como la Coca-Cola, desde el hotel más lujoso hasta en el más pinchurriento; desde Tijuana hasta Cancún había nuestros productos. 
17. También le vendíamos la salsa para las papas a Sabritas y Barcel. Valentina sintió pasos en la azotea y sacó un sobrecito de 10 gramos de su salsa. 
18. Le vendíamos a Nabisco el caramelo para su flan. La base de tomate para su pizza a Domino’s. Alsea apenas comenzaba, se llamaba DIA y tenía su almacén al Oriente de la ciudad, en San Lorenzo Tezonco. Por ahí siempre estaban Cosme y Alberto Torrado, yo negociaba con Cosme. Todavía no compraban Starbucks. Ahora están en los cuernos de la luna. 
19. También eran mis clientes todas las escuelas militares, líneas aéreas, comedores industriales, McDonal’s, Burger King y a Sam’s. Ahí conocí como comprador a Eugenio Ebrard, carnal de Marcelo. Era un perro para negociar. Con él no había de otra o “te bajaba los calzones” o te los bajabas.
20. Abal me enseñó a negociar, a aquilatar el valor del dinero. Por ejemplo, Sabritas nos compraba 120 millones de sobrecitos de salsa para sus papas y cada sobre costaba 80 centavos y nos pedían descuento. En 120 millones, un centavo es un centavo. 
21. Mientras proyectaba las ventas escribía mis poemas y mi primera novela, El orden infinito. También aprendí a aquilatar cada palabra. La lectura y la poesía fueron mi punto de fuga. Mi tabla de salvación. 
22. Para ese entonces teníamos más de 60 productos: mermelada de fresa, chabacano, cátsup, mostaza y mayonesa. Miel de abeja y de maple, salsas picantes, BBQ y agridulce, sal y pimienta. Habíamos rentado la bodega de al lado, la del otro lado, la de atrás y la de enfrente. Dábamos trabajo a 500 personas. 
23. Teníamos personal capacitado: ingenieros en alimentos que desarrollaban nuevos productos, departamento de mercadotecnia, fuerza de ventas, línea de producción que trabajaba 24 horas. Mi hermano en la fábrica y yo dirigiendo las ventas, con distribuidores en todo el país.
24. Mi hermano era el primero que llegaba a trabajar, a las 7 de la mañana, y era el último en irse, a las 9 o 10 de la noche. Lo suyo era el ruido de las máquinas, las proyecciones, las finanzas. Sólo los contables, Elsa Noemi Gómez y Felipe C Aceves se iban después de él. 
25. Mónica era el brazo derecho del gerente de la planta. Mi equipo de ventas estaba en la CDMX. Mi primer gerente de ventas fue Hugo Aboytes, luego sería Eduardo Lagunes Vazquez. Los que trabajaron conmigo estuvieron 10 o 15 años. A algunos les pagamos la universidad, aprendieron inglés. Sólo tenían que solicitarlo y los becábamos. Éramos una gran familia. 
26. Asimismo, una vez al mes desayunaba con don Lorenzo Servitje y otros empresarios de su calado en el Club de Industriales. Cuando a mi hermano le llegó la invitación (sólo eran dueños de empresas) no quiso ir y me dijo, ve tú, a ti que te gusta la farándula, yo no tengo tiempo. 
27. Como les dije, lo de él eran las máquinas, la fábrica. Don Lorenzo quería hacer empresarios socialmente responsables, pero en realidad, era un grupo súper católico que pretendía inculcarnos cómo “catequizar” a nuestro personal. De güeva pero se desayunaba muy bien. 
28. Cuando mi hermano tenía 42 años y yo 38 decidimos vender la empresa. Él ahora se dedica a otra cosa completamente distinta y yo también. A esa edad comencé a escribir de tiempo completo y a meterme cada vez en el mundo de los libros. 
29. Escribo esto en respuesta a quienes afirman que no hay empresarios buenos o que todos son una secta de capitalistas rampantes. Yo fui empresario 18 años y 15 años después, aún invito a comer a mi casa, una vez al año, a quienes trabajaron conmigo, Claudia Botello, José Ramirez y Rafa Cardozo.
30. En ese tiempo conocí a grandes empresarios que como mi hermano y como yo empezaron con nada. Gente honrada y trabajadora, disciplinada. Basta ya de polarizar, señor López Obrador, ser empresario en este país es ir contracorriente. Todo esta planeado para que fracases, y crear una industria que dé de comer a 500 familias, pagar una nómina así cada semana no es cosa sencilla.
32. En 1987 empezamos mi hermano y yo una empresa. En 2005 Abal, SA de CV era la número uno de su ramo en el país y tenía 500 empleados. La levantamos de la nada y no pisamos a nadie ni dimos mordidas ni chayote. Con trabajo y disciplina se hace uno empresario o escritor en esta vida. 

