            <article class="editorial-body">
                <p class="drop-cap">Fui empresario hasta los 38 años. Enrique, mi hermano, y yo fundamos una empresa de alimentos cuando él tenía 24 y yo 20. Yo estudiaba Ciencias de la Comunicación y él era ingeniero analista de tiempos y movimientos en Banca Serfín. Un día se preguntó por qué no había miel de abeja en porción individual, así como la mermelada y la mantequilla. Nosotros teníamos abejas desde que éramos niños en Tequila. Así que diseñó unas máquinas. Fue con el tornero, el laminero, y con su segundo sueldo compró un compresor.</p> 

                <p>Él mismo armó las máquinas y, cuando creyó que estaban listas, pidió un préstamo en su trabajo: 30 mil pesos (30 millones en aquel entonces) con intereses de empleado. Ya había planeado salirse de Serfín y negoció con su jefe que le sostuvieran esos intereses un año más. Con ese capital comenzamos él y yo. Luego contratamos a una empleada, Mónica Ramírez, que estaría con nosotros hasta el final, 18 años después. Las máquinas las instalamos en un cuarto de vecindad de 50 metros cuadrados en la Zona Roja de la ciudad. A la vuelta estaba el Guadalajara de Día.</p>
                
                <p>Con esas máquinas manuales producíamos al día 6 cajas de 400 piezas de 30 gramos de miel. Yo era el único vendedor y, en mis horas libres de la universidad, llenaba mi Vocho 66 con cajas y vendía en cafeterías, clubes deportivos y hoteles de Guadalajara.</p>
                
                <p>Pero nadie me compraba nada. Llegamos a tener un inventario de 300 cajas en almacén. Conocí la importancia de un compresor: las porciones individuales eran imposibles de abrirse. Ni con cuchillo. Pero teníamos que pagar la renta y la nómina de las 7 empleadas que ya teníamos. Las mujeres siempre fueron las mejores trabajadoras: responsables, puntuales, comprometidas. Mi hermano rediseñó sus máquinas. Se pasaba horas armándolas y desarmándolas hasta que dio con la temperatura para el sellado.</p>
                
                <p>El negocio creció y nos mudamos a una bodega de 250 metros cuadrados en Zapopan. Ya teníamos 14 obreras, entre ellas Saile Fonck, pero los clientes no se multiplicaban con la misma velocidad. El mercado nos pedía mermelada de fresa y la incluimos. Todo lo comprábamos hecho; nosotros sólo envasábamos.</p>

                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/en-mi-otra-vida-rodolfo-naro.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="Mermelada de chabacano, primeros productos de Abal">
                    <figcaption>Los primeros productos que marcaron el inicio de Abal, SA de CV.</figcaption>
                </figure>
                
                <p>En 1992 dimos el gran salto. Mi hermano consiguió otro préstamo con el banco y su aval fue el papá de un amigo que tenía una gran empresa de refrigeración, Reacsa. A don Ricardo Martínez le admiraba mucho el tesón de mi hermano. Serfín otra vez nos prestó, pero ahora fueron 350 mil dólares. Con esa línea de crédito compramos una máquina italiana. El Ferrari de las máquinas. Podía producir 1500 cajas de 240 piezas de 20 gramos en una hora.</p>
                
                <p>Nos mudamos a una bodega de mil metros cuadrados en la Zona Industrial de Guadalajara, a la cual, como si fuera a pasar el Metrobús, tuvimos que cambiarle el piso a uno de concreto para que aguantara el peso. Estábamos a pocas calles de Jabón Lirio y Salsa Valentina. Entonces sí nos sentimos empresarios. Ya teníamos 50 obreros.</p>
                
                <p>Comenzamos a fabricar todo: comprábamos la fresa en Zamora (llegamos a comprar 600 toneladas a la semana), el azúcar, la pectina y hacíamos nuestra propia mermelada. Guadalajara nos quedó chiquita y el 27 de julio de 1992 me mudé a vivir a la Ciudad de México. Tenía que conseguir clientes que le dieran trabajo a esa máquina de 350 mil dólares. En ese entonces yo tenía 25 años.</p>
                
                <p>Me aventé sin coche y sin conocer la ciudad. Me movía en metro y en pesero con mis cajas de miel y mermelada. Mis primeros dos años en la gran capital no vendí nada. Tenía 25, pero parecía de 20. Los compradores de Vips, Sanborns, Toks y Cocinas del Aire eran 30 o 40 años mayores que yo. Nada de "Jóvenes Construyendo el Futuro". Yo lloraba. No vendía nada y tenía que sostener a la fábrica en Guadalajara. Caminaba la ciudad entera cargando mis cajas. Lloraba y me preguntaba: ¿qué hago aquí?</p>
                
                <blockquote>
                    "De tanto tocar puertas yo me decía: alguna se tiene que abrir. Con que entre con uno de los grandes, ya la hice."
                </blockquote>
                
                <p>Y entré. Juan Manuel Vázquez Arrieta, de Wings, fue el primero que me compró mis productos. Enseguida cayó Toks y Sanborns. Vips fue la joya de la corona. En sus mejores épocas, Vips me llegó a comprar un tráiler completo cada semana: 4 mil cajas de mermelada para sus bisquets. Directo de la fábrica a su comisariato en Rojo Gómez, sin pasar por mi almacén.</p>
                
                <p>18 años después, Abal (así se llamaba la compañía) tenía una red de distribuidores en todo el país. Éramos como la Coca-Cola: desde el hotel más lujoso hasta en el más pinchurriento; desde Tijuana hasta Cancún había nuestros productos. También le vendíamos la salsa para las papas a Sabritas y Barcel. Valentina sintió pasos en la azotea y sacó un sobrecito de 10 gramos de su salsa. Le vendíamos a Nabisco el caramelo para su flan. La base de tomate para su pizza a Domino’s. Alsea apenas comenzaba, se llamaba DIA y tenía su almacén al Oriente de la ciudad, en San Lorenzo Tezonco. Por ahí siempre estaban Cosme y Alberto Torrado; yo negociaba con Cosme. Todavía no compraban Starbucks. Ahora están en los cuernos de la luna.</p>

                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/catsup.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="Cátsup y productos de Abal">
                    <figcaption>De la cátsup a la mostaza: expandiendo el catálogo para las grandes cadenas.</figcaption>
                </figure>
                
                <p>También eran mis clientes todas las escuelas militares, líneas aéreas, comedores industriales, McDonald’s, Burger King y Sam’s. Ahí conocí como comprador a Eugenio Ebrard, carnal de Marcelo. Era un perro para negociar. Con él no había de otra: o "te bajaba los calzones" o te los bajabas. Abal me enseñó a negociar, a aquilatar el valor del dinero. Por ejemplo, Sabritas nos compraba 120 millones de sobrecitos de salsa para sus papas y cada sobre costaba 80 centavos, y nos pedían descuento. En 120 millones, un centavo es un centavo.</p>
                
                <p>Mientras proyectaba las ventas, escribía mis poemas y mi primera novela, <em>El orden infinito</em>. También aprendí a aquilatar cada palabra. La lectura y la poesía fueron mi punto de fuga. Mi tabla de salvación.</p>
                
                <p>Para ese entonces teníamos más de 60 productos: mermelada de fresa, chabacano, cátsup, mostaza y mayonesa. Miel de abeja y de maple, salsas picantes, BBQ y agridulce, sal y pimienta. Habíamos rentado la bodega de al lado, la del otro lado, la de atrás y la de enfrente. Dábamos trabajo a 500 personas. Teníamos personal capacitado: ingenieros en alimentos que desarrollaban nuevos productos, departamento de mercadotecnia, fuerza de ventas, línea de producción que trabajaba 24 horas. Mi hermano en la fábrica y yo dirigiendo las ventas, con distribuidores en todo el país.</p>
                
                <p>Mi hermano era el primero que llegaba a trabajar, a las 7 de la mañana, y era el último en irse, a las 9 o 10 de la noche. Lo suyo era el ruido de las máquinas, las proyecciones, las finanzas. Sólo los contables, Elsa Noemí Gómez y Felipe C. Aceves, se iban después de él. Mónica era el brazo derecho del gerente de la planta. Mi equipo de ventas estaba en la CDMX. Mi primer gerente de ventas fue Hugo Aboytes, luego sería Eduardo Lagunes Vázquez. Los que trabajaron conmigo estuvieron 10 o 15 años. A algunos les pagamos la universidad, aprendieron inglés. Sólo tenían que solicitarlo y los becábamos. Éramos una gran familia.</p>
                
                <p>Asimismo, una vez al mes desayunaba con don Lorenzo Servitje y otros empresarios de su calado en el Club de Industriales. Cuando a mi hermano le llegó la invitación (sólo eran para dueños de empresas) no quiso ir y me dijo: "Ve tú, a ti que te gusta la farándula, yo no tengo tiempo". Como les dije, lo de él eran las máquinas, la fábrica. Don Lorenzo quería hacer empresarios socialmente responsables, pero en realidad era un grupo súper católico que pretendía inculcarnos cómo "catequizar" a nuestro personal. De güeva, pero se desayunaba muy bien.</p>

                <figure class="editorial-figure-inline">
                    <img src="https://lunapictures.com.mx/images/sal.jpg" 
                         loading="lazy" 
                         decoding="async" 
                         alt="Productos de sal y condimentos">
                    <figcaption>La logística de abastecer a las grandes cadenas requería precisión absoluta.</figcaption>
                </figure>
                
                <p>Cuando mi hermano tenía 42 años y yo 38, decidimos vender la empresa. Él ahora se dedica a otra cosa completamente distinta y yo también. A esa edad comencé a escribir de tiempo completo y a meterme cada vez más en el mundo de los libros.</p>
                
                <p>Escribo esto en respuesta a quienes afirman que no hay empresarios buenos o que todos son una secta de capitalistas rampantes. Yo fui empresario 18 años y, 15 años después, aún invito a comer a mi casa, una vez al año, a quienes trabajaron conmigo: Claudia Botello, José Ramírez y Rafa Cardozo.</p>
                
                <p>En ese tiempo conocí a grandes empresarios que, como mi hermano y como yo, empezaron con nada. Gente honrada, trabajadora, disciplinada. Basta ya de polarizar, señor López Obrador: ser empresario en este país es ir contracorriente. Todo está planeado para que fracases, y crear una industria que dé de comer a 500 familias, pagar una nómina así cada semana, no es cosa sencilla.</p>
                
                <p style="font-size: 1.25rem; font-weight: 600; color: #121212; margin-top: 3rem; border-top: 1px solid #e2e2e2; padding-top: 2rem;">
                    En 1987 empezamos mi hermano y yo una empresa. En 2005, Abal, SA de CV, era la número uno de su ramo en el país y tenía 500 empleados. La levantamos de la nada y no pisamos a nadie, ni dimos mordidas, ni chayote. Con trabajo y disciplina se hace uno empresario o escritor en esta vida.
                </p>

