                <div class="author-bio">
                    <h4>Sobre el autor</h4>
                    <p><strong>Rodolfo Naró</strong> nació en Tequila, Jalisco, en 1967. En 1987, su hermano y él fundaron Abal, SA de CV, en Guadalajara, y la vendieron a Heinz en 2005. Desde ese año, dejó el medio empresarial para dedicarse a la literatura.</p>
                    <p>En el 2000 fue becario del Fonca en la disciplina de narrativa. Ha escrito libros de poesía, <em>Los días inútiles</em> (1985-1995) y <em>Lo que dejó tu adiós</em> (1995-2005), así como las novelas <em>El orden infinito</em> (finalista del premio Planeta Argentina 2006 y considerada una de las mejores novelas del 2007 por la revista <em>Gatopardo</em>), <em>Cállate niña</em> y <em>Un corazón para Eva</em>.</p>
                    <p>También escribió los libros infantiles <em>Paganino</em> y <em>El misterio del colibrí</em>. Ha sido columnista de varios periódicos y revistas. Desde 2019 es miembro del Sistema Nacional de Creadores de Arte. Actualmente vive en la Ciudad de México.</p>
