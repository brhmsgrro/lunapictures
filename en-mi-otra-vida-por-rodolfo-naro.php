_________________
Rodolfo Naró nació en Tequila, Jalisco en 1967. En 1987 su hermano y él fundaron Abal, SA de CV en Guadalajara y la vendieron a Heinz en 2005. Desde ese año, dejó el medio empresarial para dedicarse a la literatura. 

En el 2000 fue becario del Fonca en la disciplina de narrativa. Ha escrito libros de poesía, Los días inútiles (1985-1995) y Lo que dejó tu adiós (1995-2005), así como las novelas, El orden infinito, finalista del premio Planeta Argentina 2006 y considerada una de las mejores novelas del 2007 por la revista Gatopardo; Cállate niña y Un corazón para Eva. 
También escribió los libros infantiles Paganino y El misterio del colibrí. Ha sido columnista de varios periódicos y revistas. Desde 2019 es miembro del Sistema Nacional de Creadores de Arte. Actualmente vive en la Ciudad de México.

