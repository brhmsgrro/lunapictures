          <p class="text-justify">También eran mis clientes todas las escuelas militares, líneas aéreas, comedores industriales, McDonal’s, Burger King y a Sam’s. Ahí conocí como comprador a Eugenio Ebrard, carnal de Marcelo. Era un perro para negociar. Con él no había de otra o “te bajaba los calzones” o te los bajabas. Abal me enseñó a negociar, a aquilatar el valor del dinero. Por ejemplo, Sabritas nos compraba 120 millones de sobrecitos de salsa para sus papas y cada sobre costaba 80 centavos y nos pedían descuento. En 120 millones, un centavo es un centavo. Mientras proyectaba las ventas escribía mis poemas y mi primera novela, El orden infinito. También aprendí a aquilatar cada palabra. La lectura y la poesía fueron mi punto de fuga. Mi tabla de salvación.  </p>

          <p class="text-justify"> Para ese entonces teníamos más de 60 productos: mermelada de fresa, chabacano, cátsup, mostaza y mayonesa. Miel de abeja y de maple, salsas picantes, BBQ y agridulce, sal y pimienta. Habíamos rentado la bodega de al lado, la del otro lado, la de atrás y la de enfrente. Dábamos trabajo a 500 personas. Teníamos personal capacitado: ingenieros en alimentos que desarrollaban nuevos productos, departamento de mercadotecnia, fuerza de ventas, línea de producción que trabajaba 24 horas. Mi hermano en la fábrica y yo dirigiendo las ventas, con distribuidores en todo el país. Mi hermano era el primero que llegaba a trabajar, a las 7 de la mañana, y era el último en irse, a las 9 o 10 de la noche. Lo suyo era el ruido de las máquinas, las proyecciones, las finanzas. Sólo los contables, Elsa Noemi Gómez y Felipe C Aceves se iban después de él. </p>
 
          <p class="text-justify">Mónica era el brazo derecho del gerente de la planta. Mi equipo de ventas estaba en la CDMX. Mi primer gerente de ventas fue Hugo Aboytes, luego sería Eduardo Lagunes Vazquez. Los que trabajaron conmigo estuvieron 10 o 15 años. A algunos les pagamos la universidad, aprendieron inglés. Sólo tenían que solicitarlo y los becábamos. Éramos una gran familia. Asimismo, una vez al mes desayunaba con don Lorenzo Servitje y otros empresarios de su calado en el Club de Industriales. Cuando a mi hermano le llegó la invitación (sólo eran dueños de empresas) no quiso ir y me dijo, ve tú, a ti que te gusta la farándula, yo no tengo tiempo.  </p>

          <p class="text-justify">Como les dije, lo de él eran las máquinas, la fábrica. Don Lorenzo quería hacer empresarios socialmente responsables, pero en realidad, era un grupo súper católico que pretendía inculcarnos cómo “catequizar” a nuestro personal. De güeva pero se desayunaba muy bien. Cuando mi hermano tenía 42 años y yo 38 decidimos vender la empresa. Él ahora se dedica a otra cosa completamente distinta y yo también. A esa edad comencé a escribir de tiempo completo y a meterme cada vez en el mundo de los libros. Escribo esto en respuesta a quienes afirman que no hay empresarios buenos o que todos son una secta de capitalistas rampantes. Yo fui empresario 18 años y 15 años después, aún invito a comer a mi casa, una vez al año, a quienes trabajaron conmigo, Claudia Botello, José Ramirez y Rafa Cardozo. </p>

           <p class="text-justify">En ese tiempo conocí a grandes empresarios que como mi hermano y como yo empezaron con nada. Gente honrada y trabajadora, disciplinada. Basta ya de polarizar, señor López Obrador, ser empresario en este país es ir contracorriente. Todo esta planeado para que fracases, y crear una industria que dé de comer a 500 familias, pagar una nómina así cada semana no es cosa sencilla. En 1987 empezamos mi hermano y yo una empresa. En 2005 Abal, SA de CV era la número uno de su ramo en el país y tenía 500 empleados. La levantamos de la nada y no pisamos a nadie ni dimos mordidas ni chayote. Con trabajo y disciplina se hace uno empresario o escritor en esta vida. </p>

