          <p class="text-justify">Él mismo armó las máquinas y cuando creyó que estaban listas pidió un préstamo en su trabajo, 30 mil pesos (30 millones en aquel entonces) con intereses de empleado. Ya había planeado salirse de Serfín y negoció con su jefe que le sostuvieran esos intereses un año más. Con ese capital comenzamos él y yo, luego contratamos a un empleada, Mónica Ramírez, que estaría con nosotros hasta el final, 18 años después. Las máquinas las instalamos en un cuarto de vecindad de 50 metros cuadrados en la Zona Roja de la ciudad. A la vuelta estaba el Guadalajara de Día.</p>

          <p class="text-justify">Con ese capital comenzamos él y yo, luego contratamos a un empleada, Mónica Ramírez, que estaría con nosotros hasta el final, 18 años después. Las máquinas las instalamos en un cuarto de vecindad de 50 metros cuadrados en la Zona Roja de la ciudad. A la vuelta estaba el Guadalajara de Día. Con esas máquinas manuales producíamos al día 6 cajas de 400 piezas de 30 gramos de miel. Yo era el único vendedor y en mis horas libres de la universidad, llenaba mi vocho 66 con cajas y vendía en cafeterías, clubes deportivos, hoteles, cafeterías de Guadalajara.</p>
          <div class="col-md-4 col-md-pull- animate-box" data-animate-effect="fadeInLeft">
          <img data-lazy="https://lunapictures.com.mx/images/catsup.jpg" class="img-responsive" alt="rodolfo naro">
          </div>
          <p class="text-justify">Pero nadie me compraba nada. Llegamos a tener un inventario de 300 cajas en almacén. Conocí la importancia de un compresor. Las porciones individuales era imposible de abrirse. Ni con cuchillo. Pero teníamos que pagar la renta y la nómina de las 7 empleadas que ya teníamos. Las mujeres siempre fueron las mejores trabajadoras. Responsables, puntuales, comprometidas. Mi hermano rediseñó sus máquinas. Se pasaba horas armándolas y desarmándolas hasta que dio con la temperatura para el sellado. </p>

          <p class="text-justify">El negocio creció y nos mudamos a una bodega de 250 metros cuadrados en Zapopan. Ya teníamos 14 obreras, entre ellas Saile Fonck, pero los clientes no se multiplicaban con la misma velocidad. El mercado nos pedía mermelada de fresa y la incluimos. Todo lo comprábamos hecho, nosotros sólo envasábamos. En 1992 dimos el gran salto. Mi hermano consiguió otro préstamo con el banco y su aval fue el papá de un amigo que tenía una gran empresa de refrigeración, Reacsa. A don Ricardo Martínez le admiraba mucho el tesón de mi hermano.  </p>

          <p class="text-justify">Serfín otra vez nos prestó, pero ahora fueron 350 mil dólares. Con esa línea de crédito compramos una máquina italiana. El Ferrari de las máquinas. Podía producir 1500 cajas de 240 piezas de 20 gramos en una hora. Nos mudamos a una bodega de mil metros cuadrados en la Zona Industria de Guadalajara, a la cual, como si fuera a pasar el Metrobús, tuvimos que cambiarle el piso a uno de concreto, para que aguantara el peso. Estábamos a pocas calles estaba Jabón Lirio y Salsa Valentina. Entonces sí nos sentimos empresarios. Ya teníamos 50 obreros. </p>

          <p class="text-justify">Comenzamos a fabricar todo: comprábamos la fresa en Zamora (llegamos a comprar 600 toneladas a la semana), el azúcar, la pectina y hacíamos nuestra propia mermelada. Guadalajara nos quedó chiquita y el 27 de julio de 1992 me mudé a vivir a la Ciudad de México. Tenía que conseguir clientes que le dieran trabajo a esa máquina de 350 mil dólares. En ese entonces yo tenía 25 años. Me aventé sin coche y sin conocer la ciudad. Me movía en metro y en pesero con mis cajas de miel y mermelada. Mis primeros dos años en la gran capital no vendí nada. Tenía 25 pero parecía de 20. Los compradores de Vips, Sanborns, Toks, Cocinas del Aire, eran 30 o 40 años mayores que yo. Nada de Jóvenes Construyendo el Futuro. Yo lloraba. No vendía nada y tenía que sostener a la fábrica en Guadalajara. Caminaba la ciudad entera cargando mis cajas. Lloraba y me preguntaba qué hago aquí.</p>

          <p class="text-justify">De tanto tocar puertas yo me decía: alguna se tiene que abrir, con que entre con uno de los grandes ya la hice. Y entré. Juan Manuel Vazquez Arrieta de Wings fue el primero que me compró mis productos. Enseguida cayó Toks y Sanborns. Vips fue la joya de la corona. En sus mejores épocas, Vips me llegó a comprar un tráiler completo cada semana. 4 mil cajas de mermelada para sus bisquets. Directo de la fábrica a su comisariato en Rojo Gómez, sin pasar por mi almacén. </p>


          <p class="text-justify">18 años después, Abal (así se llamaba la compañía) tenía una red de distribuidores en todo el país. Éramos como la Coca-Cola, desde el hotel más lujoso hasta en el más pinchurriento; desde Tijuana hasta Cancún había nuestros productos. También le vendíamos la salsa para las papas a Sabritas y Barcel. Valentina sintió pasos en la azotea y sacó un sobrecito de 10 gramos de su salsa. Le vendíamos a Nabisco el caramelo para su flan. La base de tomate para su pizza a Domino’s. Alsea apenas comenzaba, se llamaba DIA y tenía su almacén al Oriente de la ciudad, en San Lorenzo Tezonco. Por ahí siempre estaban Cosme y Alberto Torrado, yo negociaba con Cosme. Todavía no compraban Starbucks. Ahora están en los cuernos de la luna. </p>

